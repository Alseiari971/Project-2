// Arabic in Unity games through BepInEx (the mod loader) and
// XUnity.AutoTranslator (which swaps the game's text as it's drawn).
//
// GameShelf writes the AutoTranslator settings itself rather than taking them
// from a pack, so the rules can't be changed by a pack: no translation service
// at all (nothing is sent anywhere, and nothing is translated by machine), only
// the pack's compiled dictionary, which is a hash lookup, so no delay. The
// dictionary already holds shaped, screen-ordered Arabic (see
// localization/arabic_compiler), because Unity's text can't shape Arabic.
const AUTO_TRANSLATOR_CONFIG = 'BepInEx/config/AutoTranslatorConfig.ini';
const DICTIONARY = 'BepInEx/Translation/ar/Text/_AutoGeneratedTranslations.txt';

// What BepInEx and XUnity create while the game runs. Removed along with the
// mod when GameShelf created the folder they're in.
const GENERATED = [
  'BepInEx/cache',
  'BepInEx/config',
  'BepInEx/interop',
  'BepInEx/unity-libs',
  'BepInEx/Translation',
  'BepInEx/LogOutput.log',
  'BepInEx/ErrorLog.log',
];

/**
 * The XUnity.AutoTranslator settings. `fontBundle` is the TextMeshPro font
 * asset bundle in the game's folder with the Arabic Presentation Forms-B
 * glyphs, used where the game's own fonts lack them. `uguiFont` optionally
 * replaces the font of Unity's older UI text (a Windows font such as Arial).
 */
function autoTranslatorConfig({ fontBundle = '', uguiFont = '' } = {}) {
  const clean = (value) => String(value).replace(/[\r\n]/g, '');
  return [
    '; Written by GameShelf for Arabic subtitles. It\'s rewritten each time Arabic is turned on.',
    '; No translation service: only the dictionary in Translation\\ar\\Text is used.',
    '[Service]',
    'Endpoint=',
    'FallbackEndpoint=',
    '',
    '[General]',
    'Language=ar',
    'FromLanguage=en',
    '',
    '[Files]',
    'Directory=Translation\\{Lang}\\Text',
    'OutputFile=Translation\\{Lang}\\Text\\_AutoGeneratedTranslations.txt',
    '',
    '[TextFrameworks]',
    'EnableIMGUI=False',
    'EnableUGUI=True',
    'EnableNGUI=True',
    'EnableTextMeshPro=True',
    'EnableTextMesh=True',
    'EnableFairyGUI=True',
    '',
    '[Behaviour]',
    // The dictionary holds whole lines, tags included, already shaped and
    // wrapped, so XUnity must look them up as they are.
    'HandleRichText=False',
    'IgnoreWhitespaceInDialogue=False',
    'IgnoreWhitespaceInNGUI=False',
    'UseStaticTranslations=False',
    'GeneratePartialTranslations=False',
    'OutputUntranslatableText=False',
    'EnableUIResizing=True',
    'EnableSilentMode=True',
    'CopyToClipboard=False',
    `OverrideFont=${clean(uguiFont)}`,
    'OverrideFontTextMeshPro=',
    `FallbackFontTextMeshPro=${clean(fontBundle)}`,
    '',
    '[Texture]',
    'EnableTextureTranslation=False',
    'EnableTextureDumping=False',
    '',
    '[Debug]',
    'EnableConsole=False',
    '',
  ].join('\r\n');
}

/** Why a pack can't go into this Unity game, or null when it can. */
function unityMismatch(unity, requires = {}) {
  if (requires.unityBackend && requires.unityBackend !== unity.backend) {
    return `This pack is for ${requires.unityBackend === 'il2cpp' ? 'IL2CPP' : 'Mono'} Unity games, and this game uses ${unity.backend === 'il2cpp' ? 'IL2CPP' : 'Mono'}.`;
  }
  if (requires.unityVersion && !(unity.version || '').startsWith(requires.unityVersion)) {
    return `This pack is for Unity ${requires.unityVersion}, and this game uses Unity ${unity.version || 'of an unknown version'}.`;
  }
  return null;
}

module.exports = { AUTO_TRANSLATOR_CONFIG, DICTIONARY, GENERATED, autoTranslatorConfig, unityMismatch };
