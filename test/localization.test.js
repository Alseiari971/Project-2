const { publicKey, privateKey } = crypto.generateKeyPairSync('ed25519');

// A Windows program header for the given CPU (0x8664 = x64).
function program(machine = 0x8664) {
  const b = Buffer.alloc(512);
  b.write('MZ', 0, 'latin1');
  b.writeUInt32LE(0x80, 0x3c);
  b.write('PE\0\0', 0x80, 'latin1');
  b.writeUInt16LE(machine, 0x84);
  return b;
}

async function tree(files) {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'gs-game-'));
  for (const [name, content] of Object.entries(files)) {
    const file = path.join(root, name);
    if (name.endsWith('/')) {
      await fs.mkdir(file, { recursive: true });
    } else {
      await fs.mkdir(path.dirname(file), { recursive: true });
      await fs.writeFile(file, content ?? 'x');
    }
  }
  return root;
}

const unrealGame = (extra = {}) => tree({
  'MyGame.exe': program(),
  'Engine/Binaries/Win64/CrashReportClient.exe': program(),
  'MyGame/Content/Paks/pakchunk0-Windows.pak': 'game data',
  'MyGame/Binaries/Win64/MyGame-Win64-Shipping.exe': program(),
  ...extra,
});

const unityGame = (extra = {}) => tree({
  'Game.exe': program(),
  'UnityPlayer.dll': program(),
  'Game_Data/globalgamemanagers': Buffer.concat([Buffer.from([0, 0, 0, 0x16, 0, 0, 0, 0]), Buffer.from('2019.4.40f1\0', 'latin1')]),
  'Game_Data/resources.assets': 'assets',
  'Game_Data/Managed/Assembly-CSharp.dll': 'code',
  ...extra,
});

async function makePack(engine, files, details = {}) {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'gs-pack-'));
  for (const [source, content] of Object.entries(files)) {
    await fs.mkdir(path.dirname(path.join(dir, source)), { recursive: true });
    await fs.writeFile(path.join(dir, source), content);
  }
  const list = details.list || Object.keys(files).map((source) => ({ source, target: source.replace(/^payload\//, '') }));
  await writePack(dir, { id: `test-${engine}`, version: '1.0.0', engine, files: list, privateKey, ...details, list: undefined });
  return dir;
}

const unrealPack = () => makePack('unreal', { 'payload/pakchunk99-ArabicLocalization_P.pak': 'arabic text' });
const unityPack = (details) => makePack('unity', {
  'payload/winhttp.dll': program(),
  'payload/doorstop_config.ini': '[General]\nenabled=true\n',
  'payload/BepInEx/core/BepInEx.dll': 'loader',
  'payload/BepInEx/plugins/XUnity.AutoTranslator/XUnity.AutoTranslator.Plugin.Core.dll': 'plugin',
  'payload/BepInEx/Translation/ar/Text/_AutoGeneratedTranslations.txt': 'Hello=\uFE8E\uFE92\uFEA3\uFEAE\uFEE3\n',
  'payload/gameshelf_arabic_sdf': 'font bundle',
}, { fontBundle: 'gameshelf_arabic_sdf', requires: { unityBackend: 'mono' }, ...details });

const localization = async () => createLocalization({ dataDir: await fs.mkdtemp(path.join(os.tmpdir(), 'gs-data-')) });
const options = { publicKey };

// ---- Engines --------------------------------------------------------------------

test('Unreal games are recognized by Engine and Content/Paks', async () => {
  const fp = await fingerprint(await unrealGame());
  assert.equal(fp.engine, 'unreal');
  assert.equal(fp.unreal.project, 'MyGame');
  assert.match(fp.unreal.paksDir, /MyGame[\\/]Content[\\/]Paks$/);
  assert.equal(fp.unreal.arch, 'x64');
  assert.equal(fp.unreal.ioStore, false);
  assert.equal(fp.unreal.signedPaks, false);
  assert.equal((await fingerprint(await unrealGame({ 'MyGame/Content/Paks/global.utoc': 'x' }))).unreal.ioStore, true);
});

test('Unity games are recognized, with their scripting backend and version', async () => {
  const mono = await fingerprint(await unityGame());
  assert.equal(mono.engine, 'unity');
  assert.deepEqual({ ...mono.unity, exe: undefined, dataDir: undefined },
    { name: 'Game', exe: undefined, dataDir: undefined, backend: 'mono', version: '2019.4.40f1', arch: 'x64', bepinex: false, autoTranslator: false });
  const il2cpp = await fingerprint(await unityGame({ 'GameAssembly.dll': program() }));
  assert.equal(il2cpp.unity.backend, 'il2cpp');
});

test('anything else is a custom engine', async () => {
  const fp = await fingerprint(await tree({ 'game.exe': program(), 'data/world.bin': 'x' }));
  assert.equal(fp.engine, 'custom');
});

// ---- Anti-cheat guard ------------------------------------------------------------

test('anti-cheat is found where games keep it', async () => {
  const eac = await scanAntiCheat(await unrealGame({ 'MyGame/Binaries/Win64/EasyAntiCheat/Settings.json': '{}' }));
  assert.deepEqual(eac.found.map((a) => a.id), ['easyanticheat']);
  const be = await scanAntiCheat(await unityGame({ 'BattlEye/BEClient_x64.dll': 'x' }));
  assert.deepEqual(be.found.map((a) => a.id), ['battleye']);
  const cod = await scanAntiCheat(await tree({ 'cod.exe': program() }));
  assert.deepEqual(cod.found.map((a) => a.id), ['ricochet']);
  const bySteam = await scanAntiCheat(await tree({ 'game.exe': program() }), { steamAppId: 1938090 });
  assert.deepEqual(bySteam.found.map((a) => a.id), ['ricochet']);
  const clean = await scanAntiCheat(await unrealGame());
  assert.deepEqual(clean, { found: [], complete: true, problems: [] });
});

test('a check that can\'t finish counts as protected', async () => {
  const root = await unrealGame();
  assert.equal((await scanAntiCheat(root, { maxEntries: 3 })).complete, false);
  const check = await preflight(root, { maxEntries: 3 });
  assert.equal(check.tier, 'overlay');
  assert.match(check.reason, /couldn't check all/);
});

test('preflight picks a tier, and only the overlay for protected or unsupported games', async () => {
  assert.equal((await preflight(await unrealGame())).tier, 'unreal-pak');
  assert.equal((await preflight(await unityGame())).tier, 'unity-bepinex');
  const eac = await preflight(await unrealGame({ 'EasyAntiCheat/x.txt': 'x' }));
  assert.equal(eac.tier, 'overlay');
  assert.match(eac.reason, /Easy Anti-Cheat/);
  assert.equal((await preflight(await unrealGame({ 'MyGame/Content/Paks/pakchunk0-Windows.sig': 'sig' }))).tier, 'overlay');
  assert.equal((await preflight(await unityGame({ 'BepInEx/core/BepInEx.dll': 'theirs' }))).tier, 'overlay');
  assert.equal((await preflight(await tree({ 'game.exe': program() }))).tier, 'overlay');
});

// ---- Packs -----------------------------------------------------------------------

test('signed packs are read; changed or unsigned ones are refused', async () => {
  const dir = await unrealPack();
  const pack = await readPack(dir, options);
  assert.equal(pack.manifest.id, 'test-unreal');
  assert.equal(pack.files[0].target, 'pakchunk99-ArabicLocalization_P.pak');

  await assert.rejects(readPack(dir, {}), /No pack signing key/);
  await assert.rejects(readPack(dir, { publicKey: crypto.generateKeyPairSync('ed25519').publicKey }), /signature/);
  await fs.writeFile(path.join(dir, 'payload/pakchunk99-ArabicLocalization_P.pak'), 'swapped');
  await assert.rejects(readPack(dir, options), /doesn't match pack\.json/);
  await fs.rm(path.join(dir, 'pack.json.sig'));
  await assert.rejects(readPack(dir, options), /isn't signed/);
});

test('packs can only add the files their engine allows', async () => {
  const bad = (engine, target) => makePack(engine, { 'payload/f': 'x' }, { list: [{ source: 'payload/f', target }] });
  await assert.rejects(bad('unreal', '../evil_P.pak'), /plain path/);
  await assert.rejects(bad('unreal', 'pakchunk99-Arabic.pak'), /ending in _P/);
  await assert.rejects(bad('unreal', 'x_P.pak:stream'), /Windows can't use safely/);
  await assert.rejects(bad('unity', 'Game_Data/resources.assets'), /may only add BepInEx/);
  await assert.rejects(bad('unity', 'BepInEx/config/AutoTranslatorConfig.ini'), /GameShelf writes it/);
  await assert.rejects(bad('unity', 'C:/Windows/x.dll'), /relative/);
});

// ---- Adding and removing -------------------------------------------------------------

test('Unreal: the patch pak is added beside the game\'s own and removed cleanly', async () => {
  const root = await unrealGame();
  const l10n = await localization();
  const packDir = await unrealPack();
  const paks = path.join(root, 'MyGame/Content/Paks');

  const result = await l10n.enable({ root, packDir, ...options });
  assert.equal(result.tier, 'unreal-pak');
  assert.deepEqual((await fs.readdir(paks)).sort(), ['pakchunk0-Windows.pak', 'pakchunk99-ArabicLocalization_P.pak']);
  assert.equal((await l10n.status(root)).status, 'enabled');
  assert.equal((await l10n.enable({ root, packDir, ...options })).already, true);

  const off = await l10n.disable({ root });
  assert.deepEqual(off.kept, []);
  assert.deepEqual(await fs.readdir(paks), ['pakchunk0-Windows.pak']);
  assert.equal(await fs.readFile(path.join(paks, 'pakchunk0-Windows.pak'), 'utf8'), 'game data');
  assert.equal(await l10n.status(root), null);
});

test('nothing is added when a file with the same name is already there', async () => {
  const root = await unrealGame({ 'MyGame/Content/Paks/pakchunk99-ArabicLocalization_P.pak': 'someone else\'s' });
  const l10n = await localization();
  await assert.rejects(l10n.enable({ root, packDir: await unrealPack(), ...options }), (err) => err.code === 'conflict');
  assert.equal(await fs.readFile(path.join(root, 'MyGame/Content/Paks/pakchunk99-ArabicLocalization_P.pak'), 'utf8'), 'someone else\'s');
  assert.equal(await l10n.status(root), null);
});

test('Unity: BepInEx, the plugin, the dictionary and an offline-only config go in, and all come out', async () => {
  const root = await unityGame();
  const l10n = await localization();
  const result = await l10n.enable({ root, packDir: await unityPack(), ...options });
  assert.equal(result.tier, 'unity-bepinex');

  const config = await fs.readFile(path.join(root, 'BepInEx/config/AutoTranslatorConfig.ini'), 'utf8');
  assert.match(config, /^Endpoint=\r$/m);
  assert.match(config, /^FallbackEndpoint=\r$/m);
  assert.match(config, /^FallbackFontTextMeshPro=gameshelf_arabic_sdf\r$/m);
  assert.match(config, /^HandleRichText=False\r$/m);
  assert.ok(await fs.stat(path.join(root, 'BepInEx/Translation/ar/Text/_AutoGeneratedTranslations.txt')));
  assert.ok(await fs.stat(path.join(root, 'winhttp.dll')));

  // What BepInEx and XUnity do while the game runs.
  await fs.mkdir(path.join(root, 'BepInEx/cache'));
  await fs.writeFile(path.join(root, 'BepInEx/cache/chainloader_typeloader.dat'), 'cache');
  await fs.writeFile(path.join(root, 'BepInEx/LogOutput.log'), 'log');
  await fs.writeFile(path.join(root, 'BepInEx/config/BepInEx.cfg'), 'generated');
  await fs.appendFile(path.join(root, 'BepInEx/config/AutoTranslatorConfig.ini'), 'Added=ByXUnity\r\n');

  const off = await l10n.disable({ root });
  assert.deepEqual(off.kept, []);
  assert.deepEqual((await fs.readdir(root)).sort(), ['Game.exe', 'Game_Data', 'UnityPlayer.dll']);
});

test('files the player changed or added are left, and listed', async () => {
  const root = await unityGame();
  const l10n = await localization();
  await l10n.enable({ root, packDir: await unityPack(), ...options });
  await fs.writeFile(path.join(root, 'BepInEx/plugins/MyOwnMod.dll'), 'mine');
  await fs.writeFile(path.join(root, 'doorstop_config.ini'), '[General]\nenabled=false\n');

  const off = await l10n.disable({ root });
  const kept = off.kept.map((k) => path.relative(root, k.path).split(path.sep).join('/'));
  assert.ok(kept.includes('doorstop_config.ini'));
  assert.ok(kept.includes('BepInEx/plugins'));
  assert.equal(await fs.readFile(path.join(root, 'BepInEx/plugins/MyOwnMod.dll'), 'utf8'), 'mine');
  await assert.rejects(fs.stat(path.join(root, 'winhttp.dll')));
  await assert.rejects(fs.stat(path.join(root, 'BepInEx/core')));
  // Arabic can be turned on again later; the player's files are theirs now.
  await fs.rm(path.join(root, 'doorstop_config.ini'));
  assert.equal((await l10n.enable({ root, packDir: await unityPack(), ...options })).already, false);
});

test('a failed add takes back everything it wrote', async () => {
  const root = await unityGame();
  const stateDir = await fs.mkdtemp(path.join(os.tmpdir(), 'gs-state-'));
  const stager = createStager({ stateDir });
  const files = [
    { target: 'BepInEx/core/A.dll', content: 'a', sha256: sha256('a') },
    { target: 'BepInEx/core/B.dll', content: 'b', sha256: sha256('not b') }, // fails its check
  ];
  await assert.rejects(stager.enable({ root, anchor: root, pack: { id: 'p', version: '1' }, files }), /changed while it was being copied/);
  assert.deepEqual((await fs.readdir(root)).sort(), ['Game.exe', 'Game_Data', 'UnityPlayer.dll']);
  assert.deepEqual(await fs.readdir(stateDir), []);
});

test('an add cut short by a crash is taken back on the next start', async () => {
  const root = await fs.realpath(await unityGame());
  const stateDir = await fs.mkdtemp(path.join(os.tmpdir(), 'gs-state-'));
  // What a crash halfway through leaves: the record, one folder, one file.
  await fs.mkdir(path.join(root, 'BepInEx'));
  await fs.writeFile(path.join(root, 'BepInEx/A.dll'), 'a');
  await fs.writeFile(path.join(root, 'BepInEx/B.dll.op1.partial'), 'half');
  const record = {
    format: 1, root, anchor: root, pack: { id: 'p', version: '1' }, status: 'staging', op: 'op1',
    dirs: [path.join(root, 'BepInEx')],
    files: [{ path: path.join(root, 'BepInEx/A.dll'), sha256: sha256('a') }, { path: path.join(root, 'BepInEx/B.dll'), sha256: sha256('b') }],
    generated: [],
  };
  await fs.writeFile(path.join(stateDir, `${sha256(process.platform === 'win32' ? root.toLowerCase() : root).slice(0, 32)}.json`), JSON.stringify(record));

  assert.equal(await createStager({ stateDir }).recover(), 1);
  assert.deepEqual((await fs.readdir(root)).sort(), ['Game.exe', 'Game_Data', 'UnityPlayer.dll']);
});

test('games with anti-cheat are never changed', async () => {
  const root = await unrealGame({ 'MyGame/Binaries/Win64/EasyAntiCheat/x.txt': 'x' });
  const l10n = await localization();
  await assert.rejects(l10n.enable({ root, packDir: await unrealPack(), ...options }), (err) => err.code === 'blocked' && /Easy Anti-Cheat/.test(err.message));
  assert.deepEqual(await fs.readdir(path.join(root, 'MyGame/Content/Paks')), ['pakchunk0-Windows.pak']);
});

test('a running game, or a pack for another build, is refused', async () => {
  const l10n = await localization();
  await assert.rejects(l10n.enable({ root: await unrealGame(), packDir: await unrealPack(), isRunning: async () => true, ...options }), (err) => err.code === 'running');
  await assert.rejects(l10n.enable({ root: await unrealGame(), packDir: await unityPack(), ...options }), (err) => err.code === 'mismatch');
  await assert.rejects(l10n.enable({ root: await unityGame(), packDir: await unityPack({ requires: { unityBackend: 'il2cpp' } }), ...options }), /IL2CPP/);
  await assert.rejects(l10n.enable({ root: await unityGame(), packDir: await unityPack({ requires: { unityVersion: '2022.3' } }), ...options }), /Unity 2022\.3/);
});

test('files are never written through a link', { skip: process.platform === 'win32' }, async () => {
  const root = await unityGame();
  const elsewhere = await fs.mkdtemp(path.join(os.tmpdir(), 'gs-elsewhere-'));
  await fs.symlink(elsewhere, path.join(root, 'BepInEx'));
  const stager = createStager({ stateDir: await fs.mkdtemp(path.join(os.tmpdir(), 'gs-state-')) });
  await assert.rejects(
    stager.enable({ root, anchor: root, pack: { id: 'p', version: '1' }, files: [{ target: 'BepInEx/core/A.dll', content: 'a', sha256: sha256('a') }] }),
    (err) => err.code === 'conflict',
  );
  assert.deepEqual(await fs.readdir(elsewhere), []);
});

