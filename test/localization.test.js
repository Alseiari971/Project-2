const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');

const { scanAntiCheat } = require('../desktop/localization/anticheat');
const { fingerprint } = require('../desktop/localization/engine');
const { readPack, writePack } = require('../desktop/localization/pack');
const { createStager } = require('../desktop/localization/stager');
const { autoTranslatorConfig } = require('../desktop/localization/unity');
