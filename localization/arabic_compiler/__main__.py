"""Compile a game's Arabic translations for engines that can't shape Arabic.

    python -m arabic_compiler translations.csv --out build/elden-ring

The input is a CSV with "source" and "arabic" columns (and optionally "key"),
or JSON: either {"English": "Arabic", ...} or [{"source": ..., "arabic": ...}].
It writes, into --out:

  _AutoGeneratedTranslations.txt  the XUnity.AutoTranslator dictionary (Unity games)
  compiled.csv                    key, source, compiled (for Unreal .locres tools)
  compiled.json                   {source: compiled}
  charset.txt                     every non-ASCII glyph used, for building the font
  fingerprints.json               the subtitle overlay's lookup table: fingerprints
                                  of the English (not the English itself) and the
                                  Arabic in reading order, for the app to shape
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

from .fingerprint import build_table
from .rtl import DEFAULT_MAX_LINE, ArabicCompiler, UnshapedTextError, glyphs_needed
from .xunity import FILE_NAME, write_translations


def read_rows(path: Path) -> list:
    """(key, source, arabic) rows from a CSV or JSON file."""
    if path.suffix.lower() == '.json':
        data = json.loads(path.read_text(encoding='utf-8-sig'))
        if isinstance(data, dict):
            return [(None, source, arabic) for source, arabic in data.items()]
        return [(row.get('key'), row['source'], row['arabic']) for row in data]
    with path.open(encoding='utf-8-sig', newline='') as f:
        reader = csv.DictReader(f)
        missing = {'source', 'arabic'} - set(reader.fieldnames or [])
        if missing:
            raise SystemExit(f'{path} needs these columns: {", ".join(sorted(missing))}')
        return [(row.get('key') or None, row['source'], row['arabic']) for row in reader]


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(prog='python -m arabic_compiler', description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('input', type=Path, help='CSV or JSON with the translations')
    parser.add_argument('--out', type=Path, required=True, help='folder to write into')
    parser.add_argument('--max-line', type=int, default=DEFAULT_MAX_LINE,
                        help=f'wrap lines longer than this many characters (default {DEFAULT_MAX_LINE})')
    parser.add_argument('--line-break', help='what to put between wrapped lines (default: what the text uses)')
    parser.add_argument('--keep-harakat', action='store_true', help='keep vowel marks (most game fonts lack them)')
    parser.add_argument('--strict', action='store_true', help='fail on letters without a Forms-B glyph')
    args = parser.parse_args(argv)

    compiler = ArabicCompiler(max_line=args.max_line, line_break=args.line_break,
                              keep_harakat=args.keep_harakat, strict=args.strict)
    rows = read_rows(args.input)
    compiled, problems = [], 0
    for number, (key, source, arabic) in enumerate(rows, start=1):
        try:
            result = compiler.compile(arabic)
        except UnshapedTextError as err:
            print(f'row {number}: {err}', file=sys.stderr)
            problems += 1
            continue
        for warning in result.warnings:
            print(f'row {number}: {warning}', file=sys.stderr)
        compiled.append((key, source, result.text))

    args.out.mkdir(parents=True, exist_ok=True)
    written = write_translations(((s, c) for _, s, c in compiled), args.out / FILE_NAME)
    with (args.out / 'compiled.csv').open('w', encoding='utf-8', newline='') as f:
        writer = csv.writer(f)
        writer.writerow(['key', 'source', 'compiled'])
        writer.writerows(compiled)
    (args.out / 'compiled.json').write_text(
        json.dumps({s: c for _, s, c in compiled}, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
    (args.out / 'charset.txt').write_text(glyphs_needed(c for _, _, c in compiled), encoding='utf-8')
    table, table_warnings = build_table((source, arabic) for _, source, arabic in rows)
    for warning in table_warnings:
        print(f'fingerprints, {warning}', file=sys.stderr)
    (args.out / 'fingerprints.json').write_text(json.dumps(table, ensure_ascii=False, separators=(',', ':')), encoding='utf-8')

    print(f'Compiled {len(compiled)} of {len(rows)} lines into {args.out} ({written} in {FILE_NAME}).')
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
