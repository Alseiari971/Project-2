"""Builds a signed Arabic pack for a game in one command (scripts/build-arabic-pack.py).

    1. read the English: a game folder, .locres, Unity .assets, CSV, JSON or XUnity .txt;
    2. translate what isn't translated yet (OpenAI-compatible or Gemini API,
       parallel batches, cached so a stopped run resumes for free);
    3. write translations.csv, for someone to check (run again on the edited
       CSV and only its blanks are translated);
    4. compile and lay out the pack:
       - overlay: fingerprints.json (any game, see fingerprint.py);
       - unity:   BepInEx + XUnity.AutoTranslator + the compiled dictionary and
                  an Arabic TextMeshPro font bundle;
       - unreal:  the game's .locres with the Arabic in it, packed into
                  pakchunk99-ArabicLocalization_P.pak (with repak or UnrealPak);
    5. sign it with scripts/localization-pack.js.

Unreal Engine shapes Arabic and lays it out right to left itself (when the
font has Arabic letters), so Unreal packs get plain Arabic. Unity's text and
most other engines can't, so they get the compiler's shaped text.
"""

from __future__ import annotations

import argparse
import csv
import json
import os
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path, PurePosixPath

from . import locres as locres_format
from .fingerprint import build_table
from .rtl import DEFAULT_MAX_LINE, ArabicCompiler, glyphs_needed
from .sources import SourceError, read_source
from .translate import Cache, Provider, TranslationError, Translator
from .xunity import write_translations

REPO = Path(__file__).resolve().parents[2]
SIGNER = REPO / 'scripts' / 'localization-pack.js'
PAK_NAME = 'pakchunk99-ArabicLocalization_P.pak'
DICTIONARY = 'BepInEx/Translation/ar/Text/_AutoGeneratedTranslations.txt'
UNITY_ROOT_FILES = {'winhttp.dll', 'doorstop_config.ini', '.doorstop_version'}
API_KEY_ENV = {'openai': 'OPENAI_API_KEY', 'gemini': 'GEMINI_API_KEY'}


class BuildError(RuntimeError):
    pass


def parse_args(argv=None):
    p = argparse.ArgumentParser(prog='build-arabic-pack', description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('source', help='game folder, .locres, Unity .assets, CSV, JSON or XUnity .txt')
    p.add_argument('--kind', choices=['overlay', 'unity', 'unreal'], help='what pack to make (default: from the source; overlay otherwise)')
    p.add_argument('--id', required=True, help='pack id, e.g. my-game-ar')
    p.add_argument('--version', required=True, help='pack version, e.g. 1.0.0')
    game = p.add_mutually_exclusive_group(required=True)
    game.add_argument('--steam-app-id', type=int, help='the game\'s Steam app ID')
    game.add_argument('--game-id', help='the game\'s GameShelf id')
    p.add_argument('--key', help='pack-signing.key (from scripts/localization-pack.js keygen)')
    p.add_argument('--title', help='name shown in App settings')
    p.add_argument('--out', help='output folder (default: build/arabic-packs/<id>)')

    t = p.add_argument_group('translation')
    t.add_argument('--provider', choices=['openai', 'gemini'], help='translation API')
    t.add_argument('--model', help='model name, e.g. what your provider calls its current model')
    t.add_argument('--api-base', help='API base URL (for OpenAI-compatible servers other than OpenAI)')
    t.add_argument('--api-key-env', help='environment variable holding the API key (default OPENAI_API_KEY / GEMINI_API_KEY)')
    t.add_argument('--batch', type=int, default=40, help='lines per request (default 40)')
    t.add_argument('--workers', type=int, default=4, help='requests at once (default 4)')
    t.add_argument('--context', default='', help='a sentence about the game, for the translator')
    t.add_argument('--glossary', help='CSV of "english,arabic" terms to always translate the same way')
    t.add_argument('--cache', help='translation cache file (default: <out>/translation-cache.sqlite)')
    t.add_argument('--no-json-mode', action='store_true', help='for OpenAI-compatible servers without JSON output mode')
    t.add_argument('--no-translate', action='store_true', help='don\'t call any API: use only translations already in the source or cache')
    t.add_argument('--limit', type=int, help='only the first N lines (to try things out)')
    t.add_argument('--review', action='store_true', help='stop after writing translations.csv')

    c = p.add_argument_group('pack')
    c.add_argument('--max-line', type=int, default=DEFAULT_MAX_LINE, help='wrap compiled lines longer than this (Unity)')
    c.add_argument('--threshold', type=float, help='overlay: how sure a match must be (default 0.72)')
    c.add_argument('--region', help='overlay: subtitle area as x,y,w,h shares of the window')
    c.add_argument('--text-luma', type=int, help='overlay: how bright subtitle text is (default 170)')
    c.add_argument('--dark-text', action='store_true', help='overlay: dark subtitles on light boxes')
    c.add_argument('--bepinex', help='unity: BepInEx release zip or folder (Mono or IL2CPP, to match the game)')
    c.add_argument('--autotranslator', help='unity: XUnity.AutoTranslator BepInEx release zip or folder')
    c.add_argument('--font-bundle', help='unity: TextMeshPro font asset bundle with the Arabic glyphs (see charset.txt)')
    c.add_argument('--ugui-font', help='unity: a Windows font for older UI text, e.g. Arial')
    c.add_argument('--backend', choices=['mono', 'il2cpp'], help='unity: the game\'s scripting backend')
    c.add_argument('--unity-version', help='unity: the game\'s Unity version (prefix), e.g. 2019.4')
    c.add_argument('--locres-path', help='unreal: where the .locres sits in the game, e.g. MyGame/Content/Localization/Game/en/Game.locres')
    c.add_argument('--shape', action='store_true', help='unreal: shape the Arabic anyway (for games with shaping turned off)')
    c.add_argument('--packer', choices=['repak', 'unrealpak'], help='unreal: pak tool (default: whichever is installed)')
    c.add_argument('--packer-path', help='unreal: path to repak or UnrealPak')
    c.add_argument('--pak-version', default='V11', help='unreal (repak): the game\'s pak version (default V11)')
    c.add_argument('--mount-point', default='../../../', help='unreal: pak mount point (default ../../../)')
    return p.parse_args(argv)


def read_glossary(path):
    if not path:
        return {}
    with open(path, encoding='utf-8-sig', newline='') as f:
        return {row[0].strip(): row[1].strip() for row in csv.reader(f) if len(row) >= 2 and row[0].strip() and row[0].strip().lower() != 'english'}


def translate_rows(rows, args, out: Path, log):
    """Fills in each row's Arabic; returns {source: why it failed}."""
    missing = [r.source for r in rows if not r.arabic]
    if not missing:
        return {}
    cache_path = Path(args.cache or out / 'translation-cache.sqlite')
    if args.no_translate:
        # Only what earlier runs already paid for (found by the same provider and model).
        if args.provider and args.model and cache_path.exists():
            cache = Cache(cache_path)
            try:
                translator = Translator(Provider(args.provider, args.model, None, args.api_base), cache,
                                        context=args.context, glossary=read_glossary(args.glossary))
                for row in rows:
                    row.arabic = row.arabic or cache.get(translator.cache_key(row.source))
            finally:
                cache.close()
        return {}
    if not args.provider or not args.model:
        raise BuildError(f'{len(set(missing))} lines have no Arabic yet: give --provider and --model to translate them, or --no-translate.')
    key_env = args.api_key_env or API_KEY_ENV[args.provider]
    api_key = os.environ.get(key_env)
    if not api_key and not args.api_base:
        raise BuildError(f'Set {key_env} to your API key (it\'s read from the environment, never from the command line).')
    cache = Cache(cache_path)
    try:
        translator = Translator(Provider(args.provider, args.model, api_key, args.api_base, json_mode=not args.no_json_mode), cache,
                                batch_size=args.batch, workers=args.workers, context=args.context, glossary=read_glossary(args.glossary), log=log)
        done, failed = translator.translate(missing)
    finally:
        cache.close()
    for row in rows:
        if not row.arabic:
            row.arabic = done.get(row.source)
    return failed


def write_review(rows, failed, path: Path):
    with path.open('w', encoding='utf-8', newline='') as f:
        writer = csv.writer(f)
        writer.writerow(['key', 'source', 'arabic', 'problem'])
        for r in rows:
            writer.writerow([r.key or '', r.source, r.arabic or '', failed.get(r.source, '')])


def _copy_tree(source: Path, payload: Path, log):
    """Adds a BepInEx or XUnity release (zip or folder) to the payload, keeping only what a pack may hold."""
    if source.is_dir():
        files = [(p.relative_to(source).as_posix(), p.read_bytes()) for p in sorted(source.rglob('*')) if p.is_file()]
    elif zipfile.is_zipfile(source):
        with zipfile.ZipFile(source) as archive:
            files = [(i.filename, archive.read(i.filename)) for i in archive.infolist() if not i.is_dir()]
    else:
        raise BuildError(f'{source} isn\'t a zip or a folder.')
    for name, data in files:
        rel = PurePosixPath(name)
        parts = [part for part in rel.parts if part not in ('', '.')]
        if not parts or '..' in parts or rel.is_absolute():
            continue
        lower = [part.lower() for part in parts]
        if '/'.join(lower) == 'bepinex/config/autotranslatorconfig.ini':
            continue  # GameShelf writes its own
        if not ((len(parts) > 1 and lower[0] in ('bepinex', 'dotnet')) or (len(parts) == 1 and lower[0] in UNITY_ROOT_FILES)):
            log(f'Left out {name} (packs can\'t put it in the game folder).')
            continue
        target = payload.joinpath(*parts)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)


def build_unity(pairs, args, payload: Path, compiled_dir: Path, log):
    if not args.bepinex or not args.autotranslator:
        raise BuildError('A Unity pack needs --bepinex (the BepInEx release zip: BepInEx 5 for Mono games, BepInEx 6 IL2CPP for IL2CPP games) '
                         'and --autotranslator (the XUnity.AutoTranslator BepInEx release zip), from their GitHub releases.')
    compiler = ArabicCompiler(max_line=args.max_line)
    compiled = []
    for source, arabic in pairs:
        result = compiler.compile(arabic)
        for warning in result.warnings:
            log(f'"{source[:40]}": {warning}')
        compiled.append((source, result.text))
    _copy_tree(Path(args.bepinex), payload, log)
    _copy_tree(Path(args.autotranslator), payload, log)
    write_translations(compiled, payload / DICTIONARY)
    (compiled_dir / 'charset.txt').write_text(glyphs_needed(c for _, c in compiled), encoding='utf-8')
    if args.font_bundle:
        bundle = Path(args.font_bundle)
        shutil.copyfile(bundle, payload / bundle.name)
    else:
        log('No --font-bundle: TextMeshPro text will show boxes unless the game\'s fonts have Arabic. Build one from charset.txt.')


def find_packer(args):
    if args.packer_path:
        return args.packer or ('unrealpak' if 'unrealpak' in Path(args.packer_path).name.lower() else 'repak'), args.packer_path
    for kind, names in (('repak', ['repak']), ('unrealpak', ['UnrealPak', 'UnrealPak.exe'])):
        if args.packer and args.packer != kind:
            continue
        for name in names:
            found = shutil.which(name)
            if found:
                return kind, found
    return None, None


def build_unreal(source, translations: dict, args, payload: Path, stage_root: Path, log):
    if source.locres is None:
        raise BuildError('An Unreal pack needs the game\'s English .locres as the source.')
    in_pak = args.locres_path or source.locres_path
    if not in_pak:
        raise BuildError('Say where the .locres goes in the game with --locres-path, e.g. MyGame/Content/Localization/Game/en/Game.locres.')
    in_pak = PurePosixPath(in_pak.replace('\\', '/').lstrip('/'))
    if '..' in in_pak.parts:
        raise BuildError('--locres-path must stay inside the game.')
    compiler = ArabicCompiler(max_line=args.max_line) if args.shape else None
    texts = {key: (compiler(arabic) if compiler else arabic) for key, arabic in translations.items()}
    stage = stage_root / 'pak'
    shutil.rmtree(stage, ignore_errors=True)
    target = stage.joinpath(*in_pak.parts)
    target.parent.mkdir(parents=True)
    target.write_bytes(locres_format.write(source.locres.translated(texts)))
    log(f'Staged {in_pak} with {len(texts)} Arabic lines.')

    kind, exe = find_packer(args)
    if not exe:
        raise BuildError(f'The .locres is staged in {stage}, but no pak tool was found. Install repak '
                         '(github.com/trumank/repak) or give --packer-path to UnrealPak from your Unreal Engine install, then run again.')
    out_pak = payload / PAK_NAME
    if kind == 'unrealpak':
        listing = stage_root / 'unrealpak-files.txt'
        listing.write_text(f'"{target}" "{args.mount_point}{in_pak.as_posix()}"\n', encoding='utf-8')
        command = [exe, str(out_pak), f'-create={listing}']
    else:
        command = [exe, 'pack', '--version', args.pak_version, '--mount-point', args.mount_point, str(stage), str(out_pak)]
    log('Packing: ' + ' '.join(command))
    result = subprocess.run(command, capture_output=True, text=True)
    if result.returncode != 0 or not out_pak.exists():
        raise BuildError(f'{kind} failed: {(result.stderr or result.stdout).strip()[-500:]}')


def sign(pack_dir: Path, args, kind: str):
    node = shutil.which('node')
    if not node:
        raise BuildError('Signing needs Node.js (node) on the PATH.')
    command = [node, str(SIGNER), 'make', str(pack_dir), '--engine', kind, '--id', args.id, '--version', args.version, '--key', args.key]
    command += ['--steam-app-id', str(args.steam_app_id)] if args.steam_app_id else ['--game-id', args.game_id]
    if args.title:
        command += ['--title', args.title]
    if kind == 'overlay':
        for flag, value in (('--threshold', args.threshold), ('--region', args.region), ('--text-luma', args.text_luma)):
            if value is not None:
                command += [flag, str(value)]
        if args.dark_text:
            command += ['--dark-text']
    if kind == 'unity':
        if args.font_bundle:
            command += ['--font-bundle', Path(args.font_bundle).name]
        for flag, value in (('--backend', args.backend), ('--unity', args.unity_version), ('--ugui-font', args.ugui_font)):
            if value:
                command += [flag, value]
    result = subprocess.run(command, capture_output=True, text=True)
    if result.returncode != 0:
        raise BuildError(f'Signing failed: {(result.stderr or result.stdout).strip()}')
    return result.stdout.strip()


def build(args, log=print) -> Path:
    out = Path(args.out or REPO / 'build' / 'arabic-packs' / args.id)
    out.mkdir(parents=True, exist_ok=True)
    try:
        source = read_source(args.source, locres_path=args.locres_path)
    except (SourceError, locres_format.LocResError) as err:
        raise BuildError(str(err)) from None
    for note in source.notes:
        log(note)
    kind = args.kind or source.engine or 'overlay'
    rows = source.rows[:args.limit] if args.limit else source.rows
    if not rows:
        raise BuildError('Found no English lines to translate.')
    log(f'{len(rows)} English lines; making a{"n" if kind[0] in "aeiou" else ""} {kind} pack.')

    try:
        failed = translate_rows(rows, args, out, log)
    except TranslationError as err:
        raise BuildError(str(err)) from None
    write_review(rows, failed, out / 'translations.csv')
    log(f'Wrote {out / "translations.csv"}: read it, fix what needs fixing, and run again on it to rebuild.')
    if failed:
        log(f'{len(failed)} lines couldn\'t be translated cleanly; they\'re left out (see the "problem" column).')
    if args.review:
        return out

    if not args.key:
        raise BuildError('Give --key (pack-signing.key) to sign the pack.')
    pairs = [(r.source, r.arabic) for r in rows if r.arabic]
    if len(pairs) < len(rows):
        log(f'{len(rows) - len(pairs)} lines have no Arabic and are left out of the pack.')
    if not pairs:
        raise BuildError('No lines have Arabic, so there\'s nothing to pack.')
    pack_dir = out / 'pack'
    shutil.rmtree(pack_dir, ignore_errors=True)
    payload = pack_dir / 'payload'
    payload.mkdir(parents=True)
    compiled_dir = out / 'compiled'
    compiled_dir.mkdir(exist_ok=True)

    if kind == 'overlay':
        table, warnings = build_table(pairs)
        for warning in warnings:
            log(f'fingerprints: {warning}')
        (payload / 'fingerprints.json').write_text(json.dumps(table, ensure_ascii=False, separators=(',', ':')), encoding='utf-8')
    elif kind == 'unity':
        build_unity(pairs, args, payload, compiled_dir, log)
    else:
        translations = {r.key: r.arabic for r in rows if r.arabic and r.key}
        build_unreal(source, translations, args, payload, out / 'stage', log)

    log(sign(pack_dir, args, kind))
    log(f'Done: {pack_dir} ({len(pairs)} lines). Add it in GameShelf under App settings, Arabic subtitle packs.')
    return pack_dir


def main(argv=None) -> int:
    args = parse_args(argv)
    try:
        build(args)
    except BuildError as err:
        print(f'error: {err}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
