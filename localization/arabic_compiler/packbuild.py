def read_glossary(path):
    if not path:
        return {}
    with open(path, encoding='utf-8-sig', newline='') as f:
        return {row[0].strip(): row[1].strip() for row in csv.reader(f) if len(row) >= 2 and row[0].strip() and row[0].strip().lower() != 'english'}


def shared_translate(rows, args, log) -> dict:
    """Fills in Arabic from the shared memory, and (unless --no-translate) has the server translate the rest. Returns {source: why not}."""
    auth = credentials(os.environ)
    if not auth:
        raise BuildError('Set GAMESHELF_TOKEN to an access token from your GameShelf account (Edit profile, Access tokens).')
    memory = SharedMemory(args.shared, auth)
    game = game_key(args.steam_app_id, args.game_id)
    if getattr(args, 'resolved_kind', None) == 'reengine' and not args.font_targets and not args.pak_list:
        # The game's font names, as a GameShelf admin's build found them (they're checked against the game's paks).
        try:
            fonts = memory.status(game).get('fontTargets') or []
        except SharedError:
            fonts = []
        if fonts:
            args.font_targets = ','.join(fonts)
            log(f'The server knows {len(fonts)} font names for this game.')
    # Lines with nothing to translate (numbers, placeholders) stay as they are, as with the other translators.
    wanted = list(dict.fromkeys(r.source for r in rows if not r.arabic and _LETTERS.search(_TOKENS.sub('', r.source))))
    try:
        found = memory.lookup(game, [line_hash(s) for s in wanted])
        by_hash = {line_hash(s): s for s in wanted}
        answers = {by_hash[h]: arabic for h, arabic in found.items() if h in by_hash}
        log(f'Shared memory had {len(answers)} of {len(wanted)} lines.')
        failed = {}
        rest = [s for s in wanted if s not in answers]
        if rest and not args.no_translate:
            done, failed, _ = memory.translate(game, rest, context=args.context, log=log,
                                               references=getattr(args, 'references', None) or {})
            answers.update(done)
    except SharedError as err:
        raise BuildError(str(err)) from None
    for row in rows:
        arabic = answers.get(row.source)
        # Checked here too: a broken line never goes into a pack.
        if not row.arabic and arabic and problem_with(row.source, arabic) is None:
            row.arabic = arabic
        elif not row.arabic and _LETTERS.search(_TOKENS.sub('', row.source)) is None:
            row.arabic = row.source
    return failed


def choose_unity_tools(args, log):
    """For a Unity game folder: Mono or IL2CPP (IL2CPP games have GameAssembly.dll), and the matching
    BepInEx and XUnity.AutoTranslator releases from GAMESHELF_UNITY_TOOLS (the desktop app's copies:
    bepinex-mono.zip, bepinex-il2cpp.zip, xunity-mono.zip, xunity-il2cpp.zip)."""
    folder = Path(args.source)
    if not args.backend and folder.is_dir():
        args.backend = 'il2cpp' if (folder / 'GameAssembly.dll').exists() else 'mono'
        log(f'A Unity {"IL2CPP" if args.backend == "il2cpp" else "Mono"} game.')
    tools = os.environ.get('GAMESHELF_UNITY_TOOLS')
    if tools and args.backend:
        backend = 'il2cpp' if args.backend == 'il2cpp' else 'mono'
        for attr, name in (('bepinex', f'bepinex-{backend}.zip'), ('autotranslator', f'xunity-{backend}.zip')):
            if not getattr(args, attr) and (Path(tools) / name).exists():
                setattr(args, attr, str(Path(tools) / name))


def apply_by_hash(rows, path, log):
    """Arabic by the SHA-256 of each English line, from a JSON object or a signed Arabic set ({"lines": [[hash, arabic]]})."""
    data = json.loads(Path(path).read_text(encoding='utf-8'))
    table = dict(data['lines']) if isinstance(data, dict) and isinstance(data.get('lines'), list) else data
    found = 0
    for row in rows:
        arabic = table.get(line_hash(row.source))
        if arabic and not row.arabic and problem_with(row.source, arabic) is None:
            row.arabic = arabic
            found += 1
    log(f'Arabic for {found} of {len(rows)} lines from {Path(path).name}.')


def write_build_info(out: Path, rows, args, kind):
    """build-info.json: what the desktop app sends GameShelf with the game's English (engine, font names, line counts)."""
    lines = [r.source for r in rows if _LETTERS.search(_TOKENS.sub('', r.source))]
    info = {
        'engine': kind,
        'fontTargets': list(getattr(args, 'fonts_used', None) or []),
        'lines': len(set(lines)),
        'missing': len({r.source for r in rows if not r.arabic and r.source in set(lines)}),
        'godot': args.godot if kind == 'godot' else None,
    }
    (out / 'build-info.json').write_text(json.dumps(info, indent=2), encoding='utf-8')
    # The English lines themselves, for the desktop app's submission (an admin reads them beside the Arabic).
    (out / 'english.json').write_text(json.dumps(sorted(set(lines)), ensure_ascii=False), encoding='utf-8')


def report_lines(rows, args, kind, log):
    """Tells the shared memory how many lines the game has (and, for RE Engine, its font names), so the
    desktop app can tell players when its Arabic is ready."""
    lines = {r.source for r in rows if _LETTERS.search(_TOKENS.sub('', r.source))}
    try:
        status = SharedMemory(args.shared, credentials(os.environ)).report(
            game_key(args.steam_app_id, args.game_id), total=len(lines), engine=kind, name=args.title or '',
            font_targets=getattr(args, 'fonts_used', None) or [])
        log(f'The shared memory has {status.get("translated", 0)} of this game\'s {len(lines)} lines in Arabic.')
    except SharedError as err:
        log(f'Couldn\'t tell the shared memory about this game: {err}')


def write_glossary(found: dict, out: Path, log):
    (out / 'glossary.json').write_text(json.dumps(found, ensure_ascii=False, indent=1), encoding='utf-8')
    player = found.get('player', {})
    log(f'Glossary: {len(found.get("terms", {}))} names and terms; the player is spoken to as '
        f'{player.get("gender", "unknown")}{f" ({player["name"]})" if player.get("name") else ""}.')


def shared_glossary(rows, args, out: Path, log):
    """Before the server translates: the game's glossary there (made from these lines when it has none yet)."""
    lines = [r.source for r in rows]
    try:
        found = SharedMemory(args.shared, credentials(os.environ)).glossary(
            game_key(args.steam_app_id, args.game_id), glossary_module.candidates(lines), glossary_module.samples(lines), args.context)
    except SharedError as err:
        log(f'No glossary from the shared memory: {err}')
        return
    write_glossary(glossary_module.clean(found), out, log)


def translate_rows(rows, args, out: Path, log):
    """Fills in each row's Arabic; returns {source: why it failed}."""
    missing = [r.source for r in rows if not r.arabic]
    if not missing:
        return {}
    shared_failed = {}
    if args.shared and not args.no_glossary and not args.no_translate:
        shared_glossary(rows, args, out, log)
    if args.shared:
        shared_failed = shared_translate(rows, args, log)
        # What the server couldn't do can still go to your own --provider (with --no-translate, to what it already paid for).
        if not args.provider or not args.model or all(r.arabic for r in rows):
            return shared_failed
        missing = [r.source for r in rows if not r.arabic]
    cache_path = Path(args.cache or out / 'translation-cache.sqlite')
    if args.no_translate:
        # Only what earlier runs already paid for (found by the same provider and model).
        if args.provider and args.model and cache_path.exists():
            cache = Cache(cache_path)
            try:
                translator = Translator(Provider(args.provider, args.model, None, args.api_base), cache,
                                        context=args.context, glossary=read_glossary(args.glossary),
                                        references=getattr(args, 'references', None) or {})
                for row in rows:
                    row.arabic = row.arabic or cache.get(translator.cache_key(row.source))
            finally:
                cache.close()
        still = {r.source for r in rows if not r.arabic}
        return {source: why for source, why in shared_failed.items() if source in still}
    if not args.provider or not args.model:
        raise BuildError(f'{len(set(missing))} lines have no Arabic yet: give --provider and --model to translate them, or --no-translate.')
    key_env = args.api_key_env or API_KEY_ENV[args.provider]
    api_key = os.environ.get(key_env)
    if not api_key and not args.api_base:
        raise BuildError(f'Set {key_env} to your API key (it\'s read from the environment, never from the command line).')
    cache = Cache(cache_path)
    try:
        translator = Translator(Provider(args.provider, args.model, api_key, args.api_base, json_mode=not args.no_json_mode), cache,
                                batch_size=args.batch, workers=args.workers, context=args.context, glossary=read_glossary(args.glossary), log=log,
                                references=getattr(args, 'references', None) or {})
        if not args.no_glossary:
            translator.game_glossary = local_glossary(translator, [r.source for r in rows], out, log)
        done, failed = translator.translate(missing)
    finally:
        cache.close()
    for row in rows:
        if not row.arabic:
            row.arabic = done.get(row.source)
    return failed


def local_glossary(translator, lines, out: Path, log) -> dict:
    """The game's glossary for --provider builds: <out>/glossary.json from an earlier run (edit it to fix a name), else made now."""
    saved = out / 'glossary.json'
    if saved.is_file():
        try:
            found = glossary_module.clean(json.loads(saved.read_text(encoding='utf-8')))
            log(f'Glossary: {len(found["terms"])} names and terms from {saved.name}.')
            return found
        except ValueError:
            pass
    try:
        found = translator.make_glossary(lines)
    except TranslationError as err:
        log(f'No glossary this time: {err}')
        return {}
    write_glossary(found, out, log)
    return found


def keep_previous(review: Path, log):
    """Copies translations.csv aside before a run replaces it, so fixes made in it are never lost."""
    if not review.is_file():
        return
    kept = review.with_name(f'translations-{time.strftime("%Y%m%d-%H%M%S", time.localtime(review.stat().st_mtime))}.csv')
    if not kept.exists():
        shutil.copy2(review, kept)
        log(f'Kept the previous translations.csv as {kept.name}.')


def write_review(rows, failed, path: Path, keyed=False):
    """translations.csv. For games that look their text up by key, a "lookup" column keeps that for the rebuild.
    Written with a byte order mark, so Excel opens the Arabic as Arabic, and in one step, so an
    edited copy is never left half written. Raises PermissionError while it's open in Excel."""
    temp = path.with_name(path.name + '.tmp')
    with temp.open('w', encoding='utf-8-sig', newline='') as f:
        writer = csv.writer(f)
        writer.writerow(['key', 'source', 'arabic', 'problem'] + (['lookup'] if keyed else []))
        for r in rows:
            writer.writerow([r.key or '', r.source, r.arabic or '', failed.get(r.source, '')] + (['key'] if keyed else []))
    try:
        os.replace(temp, path)
    except OSError:
        temp.unlink(missing_ok=True)
        raise


def _copy_tree(source: Path, payload: Path, log):
    """Adds a BepInEx or XUnity release (zip or folder) to the payload, keeping only what a pack may hold."""
    if source.is_dir():
        files = [(p.relative_to(source).as_posix(), p.read_bytes()) for p in sorted(source.rglob('*')) if p.is_file()]
    elif zipfile.is_zipfile(source):
        with zipfile.ZipFile(source) as archive:
            files = [(i.filename, archive.read(i.filename)) for i in archive.infolist() if not i.is_dir()]
    else:
        raise BuildError(f'{source} isn\'t a zip or a folder.')
    root = os.path.realpath(payload)
    for name, data in files:
        # Both slashes separate folders on Windows, so "BepInEx/..\\..\\x.dll" is split
        # too; drive letters, "..", absolute paths and NULs leave the file out.
        parts = [part for part in re.split(r'[\\/]', name) if part not in ('', '.')]
        if not parts or '..' in parts or name.startswith(('/', '\\')) or re.match(r'^[A-Za-z]:', name) or any(':' in p or '\0' in p for p in parts):
            continue
        lower = [part.lower() for part in parts]
        if '/'.join(lower) == 'bepinex/config/autotranslatorconfig.ini':
            continue  # GameShelf writes its own
        if not ((len(parts) > 1 and lower[0] in ('bepinex', 'dotnet')) or (len(parts) == 1 and lower[0] in UNITY_ROOT_FILES)):
            log(f'Left out {name} (packs can\'t put it in the game folder).')
            continue
        target = payload.joinpath(*parts)
        if not os.path.realpath(target).startswith(root.rstrip(os.sep) + os.sep):
            raise BuildError(f'{name} in {source.name} would land outside the pack.')
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)


def build_unity(pairs, args, payload: Path, compiled_dir: Path, log):
    if not args.bepinex or not args.autotranslator:
        raise BuildError('A Unity pack needs --bepinex (the BepInEx release zip: BepInEx 5 for Mono games, BepInEx 6 IL2CPP for IL2CPP games) '
                         'and --autotranslator (the XUnity.AutoTranslator BepInEx release zip), from their GitHub releases.')
    compiler = ArabicCompiler(max_line=args.max_line)
    compiled = []
    for source, arabic in pairs:
        result = compiler.compile(arabic)
        for warning in result.warnings:
            log(f'"{source[:40]}": {warning}')
        compiled.append((source, result.text))
    _copy_tree(Path(args.bepinex), payload, log)
    _copy_tree(Path(args.autotranslator), payload, log)
    write_translations(compiled, payload / DICTIONARY)
    (compiled_dir / 'charset.txt').write_text(glyphs_needed(c for _, c in compiled), encoding='utf-8')
    if not args.font_bundle and args.unity_editor:
        args.font_bundle = str(build_tmp_bundle(args, compiled_dir, log))
    if args.font_bundle:
        bundle = Path(args.font_bundle)
        shutil.copyfile(bundle, payload / bundle.name)
    else:
        log('No --font-bundle: TextMeshPro text will show boxes unless the game\'s fonts have Arabic. Give --unity-editor '
            '(the game\'s Unity version) to build one from the Arabic font, or build it yourself from charset.txt.')
    if not args.no_ugui_font:
        log(f'Unity UI text will use {args.ugui_font} (OverrideFont), which has Arabic letters.')


