"""Builds a signed Arabic pack for a game in one command (scripts/build-arabic-pack.py).

    1. read the English: a game folder, .locres, Unity .assets, CSV, JSON or XUnity .txt;
    2. translate what isn't translated yet (OpenAI-compatible or Gemini API,
       parallel batches, cached so a stopped run resumes for free);
    3. write translations.csv, for someone to check (run again on the edited
       CSV and only its blanks are translated);
    4. compile and lay out the pack:
       - overlay: fingerprints.json (any game, see fingerprint.py);
       - unity:   BepInEx + XUnity.AutoTranslator + the compiled dictionary and
                  an Arabic TextMeshPro font bundle;
       - unreal:  the game's .locres with the Arabic in it, and an Arabic font
                  in place of the game's own font files, packed into
                  pakchunk99-ArabicLocalization_P.pak (with repak or UnrealPak);
       - renpy:   strings.json and the Arabic font for game/tl/arabic/gameshelf;
       - godot:   strings.json and the Arabic fonts for gameshelf_arabic;
    5. sign it with scripts/localization-pack.js.

Unreal Engine, Ren'Py and Godot 4 shape Arabic and lay it out right to left
themselves (when the font has Arabic letters), so their packs get plain Arabic.
Unity's text and Godot 3 can't, so they get the compiler's shaped text.

Every pack that needs a font gets IBM Plex Sans Arabic (localization/assets/
fonts, SIL Open Font License, with its license text) unless --font says otherwise.
"""

