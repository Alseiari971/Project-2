_LEGAL = re.compile(r'©|\(c\)\s*\d{4}|all rights reserved|trademarks? of', re.I)


def legal_keys(english: dict, texts: dict) -> set:
    """The entries that are a copyright or trademark notice (©, "All rights reserved"): left in English, as games
    usually leave them, since company names and dates mixed with Arabic on one line are drawn over each other."""
    return {key for key in texts if _LEGAL.search(english.get(key) or '')}


# A paragraph laid out left to right (LRM), with the Arabic in it read right to left (RLE ... PDF).
_ARABIC_LETTER = re.compile('[\u0600-\u06FF\u0750-\u077F\uFB50-\uFDFF\uFE70-\uFEFF]')
_PARAGRAPH = re.compile(r'(\r\n|\r|\n|\\n|<br\s*/?>)')


def ltr_layout(text: str) -> str:
    """`text` with each Arabic paragraph laid out where the game puts English, for Unreal games whose text boxes
    line text up "left": Unreal turns that into "right" for a right-to-left paragraph, so Arabic in a wide box
    ends up against the box's far edge. A left-to-right mark makes the paragraph left to right, and a right-to-left
    embedding keeps the Arabic (and its «!» and «،») reading right to left inside it. Line breaks end a paragraph, so
    each one is wrapped on its own."""
    if not isinstance(text, str) or not _ARABIC_LETTER.search(text):
        return text
    parts = _PARAGRAPH.split(text)
    return ''.join(p if _PARAGRAPH.fullmatch(p) or not _ARABIC_LETTER.search(p) else f'\u200e\u202b{p}\u202c' for p in parts)


# The game's character names: Unreal text entries like Character_Main_1 ("Soul") or BossName_000.
_NAME_KEY = re.compile(r'(?:^|/)(?:Character|NPC|Npc|Speaker|BossName)_[\w-]*$')
# The entries a subtitle shows as its speaker's name. Boss and enemy names label health bars, which are plain
# text: a colour tag there would show as text, so those only get coloured inside lines.
_SPEAKER_KEY = re.compile(r'(?:^|/)(?:Character|NPC|Npc|Speaker)_[\w-]*$')
# Entries that name something (EnemyName_*, BossName_*, Item…Name, AbilityName…): labels such as the title above
# a health bar, drawn as plain text, so nothing is coloured inside them. Descriptions (…NameDes…) are lines.
_LABEL_KEY = re.compile(r'Name(?!Des)', re.I)
_TAGGED = re.compile(r'<[^<>/]+>.*?</>', re.S)
_ARABIC_WORD_CHAR = '\u0621-\u064A\u0660-\u0669\u0671-\u06D3'
_STYLE_NAME = re.compile(r'^[A-Za-z][\w.]{0,60}$')
# "auto": a colour per character, from the game's own styles (Phantom Blade Zero's style table has all of these).
NAME_PALETTE = ['Character_Yellow_Decorator2', 'Blue', 'Character_Green_Decorator2', 'Character_Purple_Decorator2', 'Character_Red_Decorator2']


def color_names(english: dict, texts: dict, style: str, speakers: bool = False, palette: list | None = None) -> tuple:
    """`texts` with the game's character names wrapped in one of its own rich text styles (<style>name</>).
    Names come from the game's character entries (Character_*, NPC_*, Speaker_*, BossName_*): their English and
    Arabic. A name is coloured in a line only where that line's English names the character, so the common word
    under a name («الروح», "the soul") stays plain elsewhere; a letter joined in front of it (و، ف، ب، ل، ك) stays
    outside the colour, and text that's already styled is left alone. With `speakers`, the character entries
    themselves (the speaker's name above a subtitle) are coloured too. With `style` "auto", each character gets a
    colour of its own from `palette`, the most mentioned first so the main characters differ, the same one in every
    line and label. Returns (texts, how many names were coloured)."""
    palette = [p for p in (palette or NAME_PALETTE) if _STYLE_NAME.match(p)]
    if not _STYLE_NAME.match(style or '') or (style == 'auto' and not palette):
        raise BuildError(f'"{style}" isn\'t a rich text style name (like Character_Yellow_Decorator2).')
    names = []
    for key, en in english.items():
        ar = texts.get(key)
        if not ar or not _NAME_KEY.search(key):
            continue
        en, ar = en.strip(), ar.strip()
        if 2 <= len(en) <= 40 and en[:1].isupper() and '<' not in ar and _ARABIC_LETTER.search(ar) and len(ar) <= 40:
            names.append((en, ar))
    names = sorted(set(names), key=lambda n: -len(n[1]))
    # Each name's two patterns are made once: the English one (is the character named in this line?) and the Arabic one.
    compiled = [(en_name, ar_name, re.compile(rf'(?<![\w]){re.escape(en_name)}(?![\w])'),
                 re.compile(rf'(?<![{_ARABIC_WORD_CHAR}])([وفبلك]?){re.escape(ar_name)}(?![{_ARABIC_WORD_CHAR}])'))
                for en_name, ar_name in names]
    label_names = {ar for _, ar in names}
    if style == 'auto':
        # The most mentioned characters first, so the main cast get different colours; ties by name, so the
        # same game gets the same colours every build.
        mentions = {ar: sum(1 for t in texts.values() if ar in t) for ar in label_names}
        order = sorted(label_names, key=lambda ar: (-mentions[ar], ar))
        style_of = {ar: palette[i % len(palette)] for i, ar in enumerate(order)}
    else:
        style_of = {ar: style for ar in label_names}
    out = dict(texts)
    count = 0
    for key, ar in texts.items():
        if _NAME_KEY.search(key):
            if speakers and _SPEAKER_KEY.search(key) and ar.strip() in label_names:
                out[key] = f'<{style_of[ar.strip()]}>{ar.strip()}</>'
                count += 1
            continue
        if _LABEL_KEY.search(key.rsplit('/', 1)[-1]):
            continue
        en = english.get(key, '')
        text = ar
        for en_name, ar_name, en_pattern, ar_pattern in compiled:
            # Cheap checks first: both names have to be in their lines at all.
            if ar_name not in text or en_name not in en or not en_pattern.search(en):
                continue
            styled = [m.span() for m in _TAGGED.finditer(text)]

            def wrap(m, ar_name=ar_name, styled=styled):
                nonlocal count
                if any(a <= m.start() < b for a, b in styled):
                    return m.group(0)
                count += 1
                return f'{m.group(1)}<{style_of[ar_name]}>{ar_name}</>'

            text = ar_pattern.sub(wrap, text)
        if text != ar:
            # A plain space next to a styled name can be dropped where the game draws it ("اهزمزوو"); a no-break
            # space never is.
            ours = '|'.join(re.escape(s) for s in set(style_of.values()))
            text = re.sub(rf' (?=<(?:{ours})>)', '\u00a0', text)
            text = re.sub(rf'(<(?:{ours})>[^<]*</>) ', '\\1\u00a0', text)
        out[key] = text
    return out, count


def stage_arabic_language(source, in_pak, target: Path, stage: Path, log) -> list:
    """Arabic as its own language: the Arabic .locres again under the "ar" culture, and "ar" in the target's
    .locmeta (its compiled cultures, which the game offers as languages). Returns what was staged, for UnrealPak."""
    staged = []
    ar_inside = in_pak.parent.parent / 'ar' / in_pak.name
    ar_path = stage.joinpath(*ar_inside.parts)
    ar_path.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(target, ar_path)
    staged.append((ar_path, ar_inside))
    meta = (source.extra or {}).get('locmeta')
    if not meta:
        log(f'Staged {ar_inside}. The game\'s .locmeta wasn\'t found, so it may not offer Arabic in its language menu.')
        return staged
    meta_inside, data = meta
    try:
        patched = locres_format.add_locmeta_culture(data, 'ar')
    except locres_format.LocResError as err:
        raise BuildError(f'{meta_inside}: {err}') from None
    meta_rel = PurePosixPath(meta_inside.replace('\\', '/').lstrip('/'))
    if patched is None:
        # No list of the game's languages to add Arabic to: leave the game's own file as it is.
        log(f'Staged {ar_inside}. {meta_rel.name} has no list of the game\'s languages, so it was left as it is.')
        return staged
    meta_path = stage.joinpath(*meta_rel.parts)
    meta_path.parent.mkdir(parents=True, exist_ok=True)
    meta_path.write_bytes(patched)
    staged.append((meta_path, meta_rel))
    log(f'Added Arabic as a language: {ar_inside}, and "ar" in {meta_rel.name} '
        f'({", ".join(locres_format.read_locmeta(patched).cultures)}).')
    return staged


def patch_style_tables(args, iostore: dict, stage_root: Path, log) -> Path | None:
    """The game's per-language style tables with an "ar" style in every row (uestyles.py), as legacy assets for to-zen.
    From --ui-assets, or taken out of the game's own containers with retoc's to-legacy."""
    legacy = Path(args.ui_assets) if getattr(args, 'ui_assets', None) else None
    if legacy is None:
        tables = sorted(set(iostore.get('style_tables') or []))
        tool = retoc.find_tool(args.retoc) or iostore.get('tool')
        version = args.ue_version
        containers = retoc.game_containers(Path(args.source))
        if not tables or not tool or not containers:
            if tables:
                log('The game\'s style tables need retoc to be taken out of its containers; give them with --ui-assets instead.')
            return None
        if not version:
            raise BuildError('Adding Arabic to the game\'s style tables needs the game\'s Unreal Engine version: give --ue-version (e.g. UE5_7).')
        legacy = stage_root / 'ui-legacy'
        shutil.rmtree(legacy, ignore_errors=True)
        legacy.mkdir(parents=True)
        paks = containers[0].parent
        for table in tables:
            name = PurePosixPath(table).stem
            try:
                result = retoc._run(tool, 'to-legacy', '--version', retoc.check_version(version), '--filter', name, str(paks), str(legacy), timeout=1800)
            except retoc.RetocError as err:
                raise BuildError(str(err)) from None
            if result.returncode != 0:
                log(f'retoc couldn\'t take out {name}: {(result.stderr or result.stdout).strip()[-300:]}')
    out = stage_root / 'ui-patched'
    shutil.rmtree(out, ignore_errors=True)
    patched = []
    for asset in sorted(legacy.rglob('*.uasset')):
        rel = asset.relative_to(legacy)
        if not uestyles.STYLE_TABLE.search(rel.as_posix()):
            continue
        try:
            added = uestyles.patch_style_asset(asset, out, rel)
        except uestyles.StyleError as err:
            log(f'{rel.name}: {err}')
            continue
        if added:
            patched.append(f'{rel.stem} ({added} styles)')
    if not patched:
        log('No per-language style table with an English style was found to add Arabic to.')
        return None
    log('Added an Arabic style to every row of: ' + ', '.join(patched) + '.')
    return out


# A menu's logo texture in English (T_Logo_V2_EN, PBZ_LOGO_English), and the menu widgets that may draw one.
MENU_LOGO_TEXTURE = re.compile(r'(?i)/(?:T_)?[\w-]*logo[\w-]*?[_-](?:EN|English)\.uasset$')
MENU_WIDGET = re.compile(r'(?i)/WB?_[\w-]*(?:StartMenu|MainMenu|TitleScreen|TitleMenu|FrontEnd)[\w-]*\.uasset$')


def stage_menu_logo(args, source, iostore: dict, stage_root: Path, log) -> Path | None:
    """The Arabic logo in the game's menu, where the menu draws an English logo texture (uetexture.py): the texture
    and the menu widget, taken out of the game's containers with retoc's to-legacy and changed in place, as legacy
    assets for to-zen. Returns their folder, or None when the game has no such menu logo."""
    listing = [line.strip() for line in (source.pak_listing or '').splitlines()]
    textures = sorted({PurePosixPath(p).stem: p for p in listing if MENU_LOGO_TEXTURE.search(p)}.items())
    widgets = sorted({PurePosixPath(p).stem: p for p in listing if MENU_WIDGET.search(p)}.items())[:8]
    if not textures or not widgets:
        return None
    tool = retoc.find_tool(args.retoc) or iostore.get('tool')
    containers = retoc.game_containers(Path(args.source))
    ffmpeg = uelogo.ffmpeg_exe()
    if not tool or not containers or not args.ue_version or not ffmpeg:
        log('The game\'s menu logo is a texture (' + ', '.join(n for n, _ in textures) + '); changing it needs retoc, ffmpeg and '
            'the game\'s Unreal Engine version (--ue-version), so the menu keeps its English logo.')
        return None
    legacy = stage_root / 'menu-legacy'
    shutil.rmtree(legacy, ignore_errors=True)
    legacy.mkdir(parents=True)
    for name, _ in widgets + textures:
        try:
            retoc._run(tool, 'to-legacy', '--version', retoc.check_version(args.ue_version), '--filter', name,
                       str(containers[0].parent), str(legacy), timeout=1800)
        except retoc.RetocError as err:
            raise BuildError(str(err)) from None
    out = stage_root / 'menu-patched'
    shutil.rmtree(out, ignore_errors=True)
    files = {p.stem: p for p in legacy.rglob('*.uasset')}
    made = []
    for widget_name, _ in widgets:
        widget = files.get(widget_name)
        if not widget or not widget.with_suffix('.uexp').is_file():
            continue
        widget_uasset, widget_uexp = widget.read_bytes(), widget.with_suffix('.uexp').read_bytes()
        try:
            used = {obj for _, obj in uetexture.package_imports(widget_uasset)}
        except uetexture.TextureError:
            continue
        changed = False
        for texture_name, _ in textures:
            texture = files.get(texture_name)
            if texture_name not in used or not texture or not texture.with_suffix('.uexp').is_file():
                continue
            try:
                at = uetexture.find_brush(widget_uasset, widget_uexp, texture_name)
                uexp = texture.with_suffix('.uexp').read_bytes()
                tex = uetexture.read_texture(uexp)
                w, h = uetexture.best_shape(tex, uelogo.png_size(Path(args.logo_image)))
                pixels = uetexture.encode(tex.pixel_format, uetexture.logo_pixels(ffmpeg, Path(args.logo_image), w, h), w, h)
                brush_w, brush_h = uetexture.brush_size(widget_uexp, at)
            except (uetexture.TextureError, uelogo.LogoError) as err:
                log(f'Menu logo {texture_name}: {err}')
                continue
            rel = texture.relative_to(legacy)
            (out / rel).parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(texture, out / rel)
            (out / rel).with_suffix('.uexp').write_bytes(uetexture.write_texture(uexp, tex, pixels, w, h))
            # The brush keeps its width and takes the texture's new shape, so the menu doesn't squash the logo.
            widget_uexp = uetexture.set_brush_size(widget_uexp, at, brush_w, round(brush_w * h / w))
            changed = True
            made.append(f'{texture_name} ({tex.width}x{tex.height} -> {w}x{h} {tex.pixel_format}) in {widget_name} '
                        f'(brush {brush_w:g}x{brush_h:g} -> {brush_w:g}x{round(brush_w * h / w)})')
        if changed:
            rel = widget.relative_to(legacy)
            (out / rel).parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(widget, out / rel)
            (out / rel).with_suffix('.uexp').write_bytes(widget_uexp)
    if not made:
        log('Found no menu that draws the English logo texture, so the menu keeps its logo.')
        return None
    log('Arabic logo in the menu: ' + '; '.join(made) + '.')
    return out


# Programs in a game's folder that aren't built with its Unreal Engine, so they can't say its version.
_NOT_UNREAL = re.compile(r'^(crashpad_handler|crashreportclient\w*|7z\w*|8za\w*|checkenv|vc_?redist\w*|dxsetup|dotnet\w*|'
                         r'easyanticheat\w*|start_protected_game|eosbootstrapper|unins\d*|cefsharp\w*|steamerrorreporter\w*)\.exe$', re.I)


def unreal_programs(folder: Path, limit: int = 8) -> list:
    """The programs of an Unreal game most likely to carry its engine version, best first: the game itself
    (<Project>/Binaries/*/*-Shipping.exe, or its biggest program), then the engine's own (UnrealCEFSubProcess.exe
    is built with the same engine). Some games keep only helper tools in Binaries/Win64, so the whole folder is looked through."""
    root = Path(folder)
    if not root.is_dir():
        return []
    found = []
    for path in root.rglob('*.exe'):
        parts = [p.lower() for p in path.relative_to(root).parts]
        if 'thirdparty' in parts or _NOT_UNREAL.match(path.name):
            continue
        try:
            size = path.stat().st_size
        except OSError:
            continue
        name = path.name.lower()
        rank = 0 if name.endswith('-shipping.exe') else 1 if 'binaries' in parts else 2 if name == 'unrealcefsubprocess.exe' else 3
        found.append((rank, -size, path))
    return [path for _, _, path in sorted(found)[:limit]]


def shipping_program(folder: Path) -> Path | None:
    """An Unreal game's program (see unreal_programs)."""
    programs = unreal_programs(folder, limit=1)
    return programs[0] if programs else None


def game_engine_version(folder: Path) -> str | None:
    """'UE5_4' from the first of the game's programs that says which Unreal Engine it was built with."""
    for program in unreal_programs(folder):
        version = retoc.engine_version(program)
        if version:
            return version
    return None


def build_zen_fonts(args, iostore: dict, payload: Path, stage_root: Path, log):
    """pakchunk99-ArabicLocalization_P.utoc/.ucas beside the Arabic .pak (retoc to-zen): with the cooked replacement
    font packages from --font-assets, or empty, for UE5 games that only mount a .pak with its own .utoc and .ucas."""
    try:
        assets = retoc.font_assets(Path(args.font_assets)) if args.font_assets else []
        if args.font_assets and not assets:
            raise BuildError(f'{args.font_assets} has no cooked .uasset files.')
        tool = retoc.find_tool(args.retoc) or iostore.get('tool')
        version = args.ue_version or game_engine_version(Path(args.source))
        if not version and tool and not assets:
            # The program hides its version (copy protection often does): match the game's own containers instead.
            # Only for an empty container: cooked font packages need the exact version, from --ue-version.
            version = retoc.version_from_containers(tool, retoc.game_containers(Path(args.source)), stage_root / 'version-probe', log)
        if not tool or not version:
            # A UE5 game skips a .pak that comes without its own .utoc and .ucas, so a pack without them
            # would say Arabic is on while the game stays in English.
            if not tool:
                raise BuildError('This Unreal Engine 5 game loads its Arabic only with a .utoc and .ucas beside the .pak, and making them '
                                 'needs retoc (github.com/trumank/retoc), which this copy of GameShelf doesn\'t have.')
            raise BuildError('This Unreal Engine 5 game loads its Arabic only with a .utoc and .ucas beside the .pak, and GameShelf '
                             'couldn\'t tell which Unreal Engine version the game uses from its programs. Give it with --ue-version (e.g. UE5_4).')
        log(f'The game uses Unreal Engine {version.replace("UE", "").replace("_", ".")}.')
        if not tool:
            raise BuildError('Putting cooked font packages into an IoStore container needs retoc (github.com/trumank/retoc): give --retoc.')
        if not version:
            raise BuildError('Couldn\'t tell the game\'s Unreal Engine version from its program: give --ue-version (e.g. UE5_4).')
        zen = stage_root / 'zen'
        shutil.rmtree(zen, ignore_errors=True)
        zen.mkdir(parents=True)
        root = Path(args.font_assets) if args.font_assets else zen
        for rel in assets:
            for ext in ('.uasset', '.uexp', '.ubulk', '.uptnl'):
                part = root.joinpath(*rel.with_suffix(ext).parts)
                if part.is_file():
                    target = zen.joinpath(*rel.with_suffix(ext).parts)
                    target.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copyfile(part, target)
        pak = payload / PAK_NAME
        before = pak.read_bytes()
        made = retoc.to_zen(tool, zen, payload / PAK_NAME.replace('.pak', '.utoc'), version, log)
        if pak.read_bytes() != before:
            raise BuildError('retoc replaced the Arabic .pak; GameShelf expected it to keep the one already there.')
    except retoc.RetocError as err:
        raise BuildError(str(err)) from None
    args.fonts_used = list(getattr(args, 'fonts_used', None) or []) + [a.as_posix() for a in assets]
    if assets:
        log(f'Put {len(assets)} cooked package{"s" if len(assets) != 1 else ""} into {made[0].name} and {made[1].name} ({version}): ' + ', '.join(a.name for a in assets))
    else:
        log(f'Made {made[0].name} and {made[1].name} ({version}) to go with the Arabic .pak.')


def sign(pack_dir: Path, args, kind: str):
    node = os.environ.get('GAMESHELF_NODE') or shutil.which('node')
    if not node:
        raise BuildError('Signing needs Node.js (node) on the PATH.')
    command = [node, str(SIGNER), 'make', str(pack_dir), '--engine', kind, '--id', args.id, '--version', args.version, '--key', args.key]
    command += ['--steam-app-id', str(args.steam_app_id)] if args.steam_app_id else ['--game-id', args.game_id]
    if args.title:
        command += ['--title', args.title]
    if kind != 'overlay':
        command += ['--font-style', 'custom' if args.font else args.font_style]
    if kind == 'overlay':
        for flag, value in (('--threshold', args.threshold), ('--region', args.region), ('--text-luma', args.text_luma)):
            if value is not None:
                command += [flag, str(value)]
        if args.dark_text:
            command += ['--dark-text']
    if kind == 'unity':
        if args.font_bundle:
            command += ['--font-bundle', Path(args.font_bundle).name]
        ugui_font = None if args.no_ugui_font else args.ugui_font
        for flag, value in (('--backend', args.backend), ('--unity', args.unity_version), ('--ugui-font', ugui_font)):
            if value:
                command += [flag, value]
    if kind == 'godot':
        command += ['--godot', str(args.godot)]
    result = safe_exec.run(command, capture_output=True, text=True)
    if result.returncode != 0:
        raise BuildError(f'Signing failed: {(result.stderr or result.stdout).strip()}')
    return result.stdout.strip()


def build(args, log=print) -> Path:
    out = Path(args.out or REPO / 'build' / 'arabic-packs' / args.id)
    out.mkdir(parents=True, exist_ok=True)
    if args.recipe:
        args.kind = 'custom'
        source = recipe_source(args, out, log)
    elif args.kind == 'runtime':
        source = runtime_source(args, log)
    else:
        try:
            source = read_source(args.source, locres_path=args.locres_path, msg_path=args.msg_path, engine=args.kind)
        except (SourceError, locres_format.LocResError) as err:
            raise BuildError(str(err)) from None
    if args.kind == 'custom' and not args.recipe:
        raise BuildError('A custom engine\'s pack needs its engine recipe (--recipe).')
    for note in source.notes:
        log(note)
    kind = args.kind or source.engine or 'overlay'
    args.resolved_kind = kind
    if kind == 'godot':
        args.godot = args.godot or source.godot_version or 4
    if kind == 'unity':
        choose_unity_tools(args, log)
    if kind == 'unreal' and source.pak_tool:
        # Read from the game's own paks: pack with the same tool, at the same pak version, and find its fonts in the same listing.
        args.packer_path = args.packer_path or source.pak_tool
        args.packer = args.packer or 'repak'
        if source.pak_version and args.pak_version == 'V11':
            args.pak_version = source.pak_version
        if source.pak_listing and not args.pak_list and not args.font_targets:
            listing = out / 'game-pak-list.txt'
            listing.write_text(source.pak_listing, encoding='utf-8')
            args.pak_list = str(listing)
    if source.game_paks:
        try:
            source.msg_files = remsg.extract_messages(source.game_paks, out / 'msg-from-game', log)
        except remsg.MsgError as err:
            raise BuildError(str(err)) from None
        if not source.msg_files:
            raise BuildError('Found no message files in the game\'s paks.')
    # RE Engine message files without dumps (for an RE Engine pack, or an
    # overlay pack made from the same text) are read with REMSG_Converter.
    if source.msg_files and not source.msg_dumps and not (kind == 'reengine' and args.msg_prebuilt):
        game_paks = source.game_paks
        source = dump_messages(source, args, out, log)
        source.game_paks = game_paks  # still needed, for the game's fonts
    # RE Engine message files that already hold the Arabic need no translating.
    prebuilt = kind == 'reengine' and args.msg_prebuilt and not source.rows
    rows = source.rows[:args.limit] if args.limit else source.rows
    if args.arabic_by_hash:
        apply_by_hash(rows, args.arabic_by_hash, log)
    if args.translations:
        apply_reviewed(rows, args.translations, log)
    learning = kind == 'runtime'  # the runtime adapter can start with no lines, and learn them in the game
    if not rows and not prebuilt and not learning:
        raise BuildError('Found no English lines to translate.')
    failed = {}
    if rows:
        log(f'{len(rows)} English lines; making a{"n" if kind[0] in "aeiou" else ""} {kind} pack.')
        try:
            # The same lines in the game's other languages, when it has them (see sources.py and locres_pivot.py).
            args.references = (source.extra or {}).get('references') or {}
            failed = translate_rows(rows, args, out, log)
        except TranslationError as err:
            raise BuildError(str(err)) from None
        review = out / 'translations.csv'
        try:
            if not args.translations or Path(args.translations).resolve() != review.resolve():
                keep_previous(review, log)
            write_review(rows, failed, review, keyed=source.keyed)
            log(f'Wrote {review}: read it, fix what needs fixing, and run again with --translations to rebuild.')
        except PermissionError:
            # Windows won't let a file open in Excel be replaced.
            if args.review:
                raise BuildError(f'{review} is open in another program (Excel?). Close it and run again.') from None
            log(f'{review} is open in another program (Excel?), so it was left as it is. The pack is made all the same.')
        if failed:
            log(f'{len(failed)} lines couldn\'t be translated cleanly; they\'re left out (see the "problem" column).')
    if args.review:
        return out

    if not args.key:
        raise BuildError('Give --key (pack-signing.key) to sign the pack.')
    pairs = [(r.source, r.arabic) for r in rows if r.arabic]
    if len(pairs) < len(rows):
        log(f'{len(rows) - len(pairs)} lines have no Arabic and are left out of the pack.')
    if not pairs and not prebuilt and not learning:
        raise BuildError('No lines have Arabic, so there\'s nothing to pack.')
    pack_dir = out / 'pack'
    shutil.rmtree(pack_dir, ignore_errors=True)
    payload = pack_dir / 'payload'
    payload.mkdir(parents=True)
    compiled_dir = out / 'compiled'
    compiled_dir.mkdir(exist_ok=True)

    if kind == 'overlay':
        table, warnings = build_table(pairs)
        for warning in warnings:
            log(f'fingerprints: {warning}')
        (payload / 'fingerprints.json').write_text(json.dumps(table, ensure_ascii=False, separators=(',', ':')), encoding='utf-8')
    elif kind == 'unity':
        build_unity(pairs, args, payload, compiled_dir, log)
    elif kind == 'renpy':
        build_renpy(pairs, args, payload, log)
    elif kind == 'godot':
        build_godot(rows, source, args, payload, log)
    elif kind == 'reengine':
        build_reengine(source, rows, args, out, payload, log)
    elif kind == 'bethesda':
        build_bethesda(source, rows, args, payload, log)
    elif kind == 'loose':
        build_loose(source, rows, args, payload, log)
    elif kind == 'custom':
        build_custom(source, rows, args, payload, log)
    elif kind == 'runtime':
        build_runtime(rows, args, payload, log)
    else:
        translations = {r.key: r.arabic for r in rows if r.arabic and r.key}
        build_unreal(source, translations, args, payload, out / 'stage', log)

    if args.shared and rows:
        report_lines(rows, args, kind, log)
    write_build_info(out, rows, args, kind)
    log(sign(pack_dir, args, kind))
    log(f'Done: {pack_dir}{f" ({len(pairs)} lines)" if pairs else ""}. Add it in GameShelf under App settings, Arabic subtitle packs.')
    return pack_dir


def main(argv=None) -> int:
    args = parse_args(argv)
    try:
        build(args)
    except BuildError as err:
        print(f'error: {err}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
