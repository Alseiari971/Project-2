def read_glossary(path):
    if not path:
        return {}
    with open(path, encoding='utf-8-sig', newline='') as f:
        return {row[0].strip(): row[1].strip() for row in csv.reader(f) if len(row) >= 2 and row[0].strip() and row[0].strip().lower() != 'english'}


def shared_translate(rows, args, log) -> dict:
    """Fills in Arabic from the shared memory, and (unless --no-translate) has the server translate the rest. Returns {source: why not}."""
    auth = credentials(os.environ)
    if not auth:
        raise BuildError('Set GAMESHELF_TOKEN to an access token from your GameShelf account (Edit profile, Access tokens).')
    memory = SharedMemory(args.shared, auth)
    game = game_key(args.steam_app_id, args.game_id)
    if getattr(args, 'resolved_kind', None) == 'reengine' and not args.font_targets and not args.pak_list:
        # The game's font names, as a GameShelf admin's build found them (they're checked against the game's paks).
        try:
            fonts = memory.status(game).get('fontTargets') or []
        except SharedError:
            fonts = []
        if fonts:
            args.font_targets = ','.join(fonts)
            log(f'The server knows {len(fonts)} font names for this game.')
    # Lines with nothing to translate (numbers, placeholders) stay as they are, as with the other translators.
    wanted = list(dict.fromkeys(r.source for r in rows if not r.arabic and _LETTERS.search(_TOKENS.sub('', r.source))))
    try:
        found = memory.lookup(game, [line_hash(s) for s in wanted])
        by_hash = {line_hash(s): s for s in wanted}
        answers = {by_hash[h]: arabic for h, arabic in found.items() if h in by_hash}
        log(f'Shared memory had {len(answers)} of {len(wanted)} lines.')
        failed = {}
        rest = [s for s in wanted if s not in answers]
        if rest and not args.no_translate:
            done, failed, _ = memory.translate(game, rest, context=args.context, log=log)
            answers.update(done)
    except SharedError as err:
        raise BuildError(str(err)) from None
    for row in rows:
        arabic = answers.get(row.source)
        # Checked here too: a broken line never goes into a pack.
        if not row.arabic and arabic and problem_with(row.source, arabic) is None:
            row.arabic = arabic
        elif not row.arabic and _LETTERS.search(_TOKENS.sub('', row.source)) is None:
            row.arabic = row.source
    return failed


def report_lines(rows, args, kind, log):
    """Tells the shared memory how many lines the game has (and, for RE Engine, its font names), so the
    desktop app can tell players when its Arabic is ready."""
    lines = {r.source for r in rows if _LETTERS.search(_TOKENS.sub('', r.source))}
    try:
        status = SharedMemory(args.shared, credentials(os.environ)).report(
            game_key(args.steam_app_id, args.game_id), total=len(lines), engine=kind, name=args.title or '',
            font_targets=getattr(args, 'fonts_used', None) or [])
        log(f'The shared memory has {status.get("translated", 0)} of this game\'s {len(lines)} lines in Arabic.')
    except SharedError as err:
        log(f'Couldn\'t tell the shared memory about this game: {err}')


def translate_rows(rows, args, out: Path, log):
    """Fills in each row's Arabic; returns {source: why it failed}."""
    missing = [r.source for r in rows if not r.arabic]
    if not missing:
        return {}
    shared_failed = {}
    if args.shared:
        shared_failed = shared_translate(rows, args, log)
        # What the server couldn't do can still go to your own --provider (with --no-translate, to what it already paid for).
        if not args.provider or not args.model or all(r.arabic for r in rows):
            return shared_failed
        missing = [r.source for r in rows if not r.arabic]
    cache_path = Path(args.cache or out / 'translation-cache.sqlite')
    if args.no_translate:
        # Only what earlier runs already paid for (found by the same provider and model).
        if args.provider and args.model and cache_path.exists():
            cache = Cache(cache_path)
            try:
                translator = Translator(Provider(args.provider, args.model, None, args.api_base), cache,
                                        context=args.context, glossary=read_glossary(args.glossary))
                for row in rows:
                    row.arabic = row.arabic or cache.get(translator.cache_key(row.source))
            finally:
                cache.close()
        still = {r.source for r in rows if not r.arabic}
        return {source: why for source, why in shared_failed.items() if source in still}
    if not args.provider or not args.model:
        raise BuildError(f'{len(set(missing))} lines have no Arabic yet: give --provider and --model to translate them, or --no-translate.')
    key_env = args.api_key_env or API_KEY_ENV[args.provider]
    api_key = os.environ.get(key_env)
    if not api_key and not args.api_base:
        raise BuildError(f'Set {key_env} to your API key (it\'s read from the environment, never from the command line).')
    cache = Cache(cache_path)
    try:
        translator = Translator(Provider(args.provider, args.model, api_key, args.api_base, json_mode=not args.no_json_mode), cache,
                                batch_size=args.batch, workers=args.workers, context=args.context, glossary=read_glossary(args.glossary), log=log)
        done, failed = translator.translate(missing)
    finally:
        cache.close()
    for row in rows:
        if not row.arabic:
            row.arabic = done.get(row.source)
    return failed


def keep_previous(review: Path, log):
    """Copies translations.csv aside before a run replaces it, so fixes made in it are never lost."""
    if not review.is_file():
        return
    kept = review.with_name(f'translations-{time.strftime("%Y%m%d-%H%M%S", time.localtime(review.stat().st_mtime))}.csv')
    if not kept.exists():
        shutil.copy2(review, kept)
        log(f'Kept the previous translations.csv as {kept.name}.')


def write_review(rows, failed, path: Path, keyed=False):
    """translations.csv. For games that look their text up by key, a "lookup" column keeps that for the rebuild.
    Written with a byte order mark, so Excel opens the Arabic as Arabic, and in one step, so an
    edited copy is never left half written. Raises PermissionError while it's open in Excel."""
    temp = path.with_name(path.name + '.tmp')
    with temp.open('w', encoding='utf-8-sig', newline='') as f:
        writer = csv.writer(f)
        writer.writerow(['key', 'source', 'arabic', 'problem'] + (['lookup'] if keyed else []))
        for r in rows:
            writer.writerow([r.key or '', r.source, r.arabic or '', failed.get(r.source, '')] + (['key'] if keyed else []))
    try:
        os.replace(temp, path)
    except OSError:
        temp.unlink(missing_ok=True)
        raise


def _copy_tree(source: Path, payload: Path, log):
    """Adds a BepInEx or XUnity release (zip or folder) to the payload, keeping only what a pack may hold."""
    if source.is_dir():
        files = [(p.relative_to(source).as_posix(), p.read_bytes()) for p in sorted(source.rglob('*')) if p.is_file()]
    elif zipfile.is_zipfile(source):
        with zipfile.ZipFile(source) as archive:
            files = [(i.filename, archive.read(i.filename)) for i in archive.infolist() if not i.is_dir()]
    else:
        raise BuildError(f'{source} isn\'t a zip or a folder.')
    for name, data in files:
        rel = PurePosixPath(name)
        parts = [part for part in rel.parts if part not in ('', '.')]
        if not parts or '..' in parts or rel.is_absolute():
            continue
        lower = [part.lower() for part in parts]
        if '/'.join(lower) == 'bepinex/config/autotranslatorconfig.ini':
            continue  # GameShelf writes its own
        if not ((len(parts) > 1 and lower[0] in ('bepinex', 'dotnet')) or (len(parts) == 1 and lower[0] in UNITY_ROOT_FILES)):
            log(f'Left out {name} (packs can\'t put it in the game folder).')
            continue
        target = payload.joinpath(*parts)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)


def build_unity(pairs, args, payload: Path, compiled_dir: Path, log):
    if not args.bepinex or not args.autotranslator:
        raise BuildError('A Unity pack needs --bepinex (the BepInEx release zip: BepInEx 5 for Mono games, BepInEx 6 IL2CPP for IL2CPP games) '
                         'and --autotranslator (the XUnity.AutoTranslator BepInEx release zip), from their GitHub releases.')
    compiler = ArabicCompiler(max_line=args.max_line)
    compiled = []
    for source, arabic in pairs:
        result = compiler.compile(arabic)
        for warning in result.warnings:
            log(f'"{source[:40]}": {warning}')
        compiled.append((source, result.text))
    _copy_tree(Path(args.bepinex), payload, log)
    _copy_tree(Path(args.autotranslator), payload, log)
    write_translations(compiled, payload / DICTIONARY)
    (compiled_dir / 'charset.txt').write_text(glyphs_needed(c for _, c in compiled), encoding='utf-8')
    if not args.font_bundle and args.unity_editor:
        args.font_bundle = str(build_tmp_bundle(args, compiled_dir, log))
    if args.font_bundle:
        bundle = Path(args.font_bundle)
        shutil.copyfile(bundle, payload / bundle.name)
    else:
        log('No --font-bundle: TextMeshPro text will show boxes unless the game\'s fonts have Arabic. Give --unity-editor '
            '(the game\'s Unity version) to build one from the Arabic font, or build it yourself from charset.txt.')
    if not args.no_ugui_font:
        log(f'Unity UI text will use {args.ugui_font} (OverrideFont), which has Arabic letters.')


# The editor script that makes the TextMeshPro font asset bundle. It runs in
# the Unity Editor in batch mode, in a throwaway project made for it.
TMP_BUNDLE_SCRIPT = r'''using System.IO;
using TMPro;
using UnityEditor;
using UnityEngine;
using UnityEngine.TextCore.LowLevel;

public static class GameShelfArabicFont
{
    public static void Build()
    {
        string[] args = System.Environment.GetCommandLineArgs();
        string output = args[System.Array.IndexOf(args, "-gameshelfOut") + 1];
        string charset = File.ReadAllText(args[System.Array.IndexOf(args, "-gameshelfCharset") + 1]);
        AssetDatabase.Refresh();
        Font font = AssetDatabase.LoadAssetAtPath<Font>("Assets/ArabicFont.ttf");
        TMP_FontAsset asset = TMP_FontAsset.CreateFontAsset(font, 90, 9, GlyphRenderMode.SDFAA, 4096, 4096, AtlasPopulationMode.Dynamic, true);
        string missing;
        asset.TryAddCharacters(charset, out missing);
        if (!string.IsNullOrEmpty(missing)) Debug.LogWarning("GameShelf: the font lacks " + missing.Length + " characters.");
        asset.atlasPopulationMode = AtlasPopulationMode.Static;
        asset.name = "@NAME@";
        AssetDatabase.CreateAsset(asset, "Assets/@NAME@.asset");
        foreach (Texture2D texture in asset.atlasTextures) { texture.name = "@NAME@ Atlas"; AssetDatabase.AddObjectToAsset(texture, asset); }
        asset.material.name = "@NAME@ Material";
        AssetDatabase.AddObjectToAsset(asset.material, asset);
        AssetDatabase.SaveAssets();
        AssetImporter.GetAtPath("Assets/@NAME@.asset").assetBundleName = "@NAME@";
        Directory.CreateDirectory(output);
        BuildPipeline.BuildAssetBundles(output, BuildAssetBundleOptions.None, BuildTarget.StandaloneWindows64);
    }
}
'''


def build_tmp_bundle(args, compiled_dir: Path, log) -> Path:
    """Builds a TextMeshPro font asset bundle from the Arabic font with the Unity Editor (same version as the game)."""
    project = compiled_dir / 'unity-font-project'
    shutil.rmtree(project, ignore_errors=True)
    (project / 'Assets' / 'Editor').mkdir(parents=True)
    (project / 'Packages').mkdir()
    (project / 'Packages' / 'manifest.json').write_text(json.dumps({'dependencies': {'com.unity.textmeshpro': '3.0.6', 'com.unity.ugui': '1.0.0'}}), encoding='utf-8')
    shutil.copyfile(args.font or DEFAULT_FONT, project / 'Assets' / 'ArabicFont.ttf')
    (project / 'Assets' / 'Editor' / 'GameShelfArabicFont.cs').write_text(TMP_BUNDLE_SCRIPT.replace('@NAME@', UNITY_FONT_BUNDLE), encoding='utf-8')
    out = compiled_dir / 'unity-font-bundle'
    command = [args.unity_editor, '-batchmode', '-nographics', '-quit', '-projectPath', str(project),
               '-executeMethod', 'GameShelfArabicFont.Build', '-logFile', str(compiled_dir / 'unity-font.log'),
               '-gameshelfOut', str(out), '-gameshelfCharset', str(compiled_dir / 'charset.txt')]
    log('Building the TextMeshPro font bundle: ' + ' '.join(command))
    result = subprocess.run(command, capture_output=True, text=True)
    bundle = out / UNITY_FONT_BUNDLE
    if result.returncode != 0 or not bundle.exists():
        raise BuildError(f'The Unity Editor couldn\'t build the font bundle; see {compiled_dir / "unity-font.log"}.')
    return bundle


def font_files(args):
    """(regular, bold, license) to pack: the given font, or the bundled IBM Plex Sans Arabic."""
    regular = Path(args.font) if args.font else DEFAULT_FONT
    bold = Path(args.font_bold) if args.font_bold else (DEFAULT_BOLD_FONT if not args.font else regular)
    license_text = Path(args.font_license) if args.font_license else (DEFAULT_FONT_LICENSE if not args.font else None)
    for path in (regular, bold):
        if path.suffix.lower() not in ('.ttf', '.otf') or not path.is_file():
            raise BuildError(f'{path} isn\'t a .ttf or .otf font file.')
    return regular, bold, license_text


def _pack_font_name(path: Path) -> str:
    return re.sub(r'[^\w.\-]', '-', path.name)


def write_data_pack(lines: dict, args, payload: Path, folder: PurePosixPath, fonts_key: str, log):
    """Ren'Py and Godot packs: strings.json, the fonts and the font's license, in one folder."""
    regular, bold, license_text = font_files(args)
    target = payload.joinpath(*folder.parts)
    target.mkdir(parents=True)
    names = {'regular': _pack_font_name(regular)}
    shutil.copyfile(regular, target / names['regular'])
    if fonts_key == 'fonts' and bold != regular:
        names['bold'] = _pack_font_name(bold)
        shutil.copyfile(bold, target / names['bold'])
    if license_text:
        shutil.copyfile(license_text, target / ('FONT-LICENSE-' + _pack_font_name(license_text).removesuffix('.txt') + '.txt'))
    else:
        log('No --font-license: include the font\'s license if it asks for that.')
    data = {'lines': lines, fonts_key: names if fonts_key == 'fonts' else names['regular']}
    (target / 'strings.json').write_text(json.dumps(data, ensure_ascii=False, indent=0), encoding='utf-8')
    log(f'Wrote {len(lines)} Arabic lines and the {regular.stem} font to {folder}.')


def build_renpy(pairs, args, payload: Path, log):
    # Ren'Py shapes and orders Arabic itself (config.rtl), so the Arabic stays as written.
    write_data_pack(dict(pairs), args, payload, RENPY_DIR, 'font', log)


def build_godot(rows, source, args, payload: Path, log):
    compiler = ArabicCompiler(max_line=args.max_line) if args.godot == 3 else None
    lines = {}
    for row in rows:
        if not row.arabic:
            continue
        message = row.key if source.keyed and row.key else row.source
        lines[message] = compiler(row.arabic) if compiler else row.arabic
    write_data_pack(lines, args, payload, GODOT_DIR, 'fonts', log)


def unreal_font_targets(args, log) -> list:
    """The game's font files to put the Arabic font in place of, as paths inside its paks."""
    if args.no_fonts:
        return []
    found = []
    if args.font_targets:
        found += [t.strip() for t in args.font_targets.split(',') if t.strip()]
    if args.pak_list:
        text = Path(args.pak_list).read_text(encoding='utf-8', errors='replace')
        found += [m.group(1).strip() for m in UNREAL_FONT.finditer(text.replace('\\', '/'))]
    if args.extracted:
        root = Path(args.extracted)
        found += [p.relative_to(root).as_posix() for p in sorted(root.rglob('*'))
                  if p.suffix.lower() in ('.ufont', '.ttf', '.otf') and 'Content' in p.relative_to(root).parts]
    targets = []
    for value in found:
        path = PurePosixPath(re.sub(r'^(\.\./)+', '', value.replace('\\', '/')).lstrip('/'))
        if '..' in path.parts or path.suffix.lower() not in ('.ufont', '.ttf', '.otf'):
            raise BuildError(f'"{value}" isn\'t a font file inside the game.')
        if path not in targets:
            targets.append(path)
    if not targets:
        log('No font files given (--pak-list, --extracted or --font-targets): the game keeps its fonts, '
            'which shows boxes for Arabic unless they have Arabic letters.')
    return targets


def apply_reviewed(rows, path, log):
    """Uses the Arabic of a checked translations.csv, matched by key, else by English."""
    with open(path, encoding='utf-8-sig', newline='') as f:
        reviewed = [r for r in csv.DictReader(f) if (r.get('arabic') or '').strip()]
    by_key = {r['key']: r['arabic'].strip() for r in reviewed if r.get('key')}
    by_source = {r['source']: r['arabic'].strip() for r in reviewed if r.get('source')}
    used = 0
    for row in rows:
        found = (by_key.get(row.key) if row.key else None) or by_source.get(row.source)
        if found:
            row.arabic = found
            used += 1
    log(f'{used} lines take their Arabic from {Path(path).name}.')


def dump_messages(source, args, out: Path, log):
    """RE Engine .msg files without dumps: has REMSG_Converter dump them."""
    if not args.msg_tool:
        raise BuildError(f'Found {len(source.msg_files)} message files and no dumps of them. Give --msg-tool (REMSG_Converter\'s '
                         'src/main.py, or its .exe) to read them, or --msg-prebuilt if they already hold the Arabic.')
    work = out / 'msg-dumps'
    shutil.rmtree(work, ignore_errors=True)
    dumps = []
    for path, in_pak in source.msg_files:
        try:
            dumps.append(remsg.export_dump(args.msg_tool, Path(path), work, in_pak))
        except remsg.MsgError as err:
            raise BuildError(str(err)) from None
    log(f'REMSG_Converter read {len(dumps)} message files.')
    return msg_dump_source(dumps)


# RE Engine message text: timing cues for cutscene subtitles come first
# (<TIME start, end>, one per page), then pages split by <PAGE>, shown one
# after another.
RE_CUES = re.compile(r'^(?:<TIME [^<>]*>)*')


RE_TAG = re.compile(r'</?[A-Z][A-Z_]*(?: [^<>\n]*)?>')


class LineWidths:
    """How wide a line is drawn in a font, from its letters' advance widths (the Arabic is already in its final letter forms)."""

    def __init__(self, font_path):
        from fontTools.ttLib import TTFont
        font = TTFont(str(font_path), lazy=True)
        self.cmap = font.getBestCmap()
        metrics = font['hmtx'].metrics
        self.advance = {cp: metrics[name][0] for cp, name in self.cmap.items()}
        self.space = self.advance.get(0x20) or font['head'].unitsPerEm // 4

    def width(self, line: str) -> int:
        return sum(self.advance.get(ord(c), 0) for c in RE_TAG.sub('', line))


def line_widths(font_path, log):
    try:
        return LineWidths(font_path)
    except ImportError:
        log('Arabic stays lined up on the left: run  pip install fonttools  to line it up on the right.')
        return None


def align_right(page: str, widths) -> str:
    """Pads the shorter lines of a page so every line ends where the longest does."""
    lines = page.split('\n')
    if len(lines) < 2:
        return page
    sizes = [widths.width(line.rstrip('\r')) for line in lines]
    longest = max(sizes)
    return '\n'.join(' ' * round((longest - size) / widths.space) + line for line, size in zip(lines, sizes))


def shape_re_text(text: str, compiler, widths=None) -> str:
    """Joins and orders each page on its own, keeping the cues first and the pages in order;
    with `widths`, lines up each page's lines on the right."""
    cues = RE_CUES.match(text).group(0)
    pages = [compiler(page) for page in text[len(cues):].split('<PAGE>')]
    if widths:
        pages = [align_right(page, widths) for page in pages]
    return cues + '<PAGE>'.join(pages)


RE_FONT = re.compile(r'^(natives/\S+\.oft(?:\.\d+)?(?:\.(?:stm|x64))?)\s*$', re.I | re.M)
RE_BOLD_FONT = re.compile(r'bold|bd\.|heavy|black|-b\.', re.I)


def re_font_targets(args, source, log) -> list:
    """The game's .oft font names to put the Arabic font under: from --font-targets and --pak-list,
    kept to the ones the game's paks hold (only their file tables are read)."""
    names = [t.strip().replace('\\', '/') for t in (args.font_targets or '').split(',') if t.strip()]
    if args.pak_list:
        names += RE_FONT.findall(Path(args.pak_list).read_text(encoding='utf-8', errors='replace'))
    names = [n for n in dict.fromkeys(names) if n.lower().startswith('natives/') and '..' not in n.split('/')]
    if not names or not source.game_paks:
        return names
    present = set()
    for path in source.game_paks:
        with GamePak(path) as pak:
            present |= set(pak.entries)
    found = [n for n in names if path_hashes(n) in present]
    log(f'{len(found)} of the {len(names)} font names given are in the game\'s paks.')
    # Games keep a font more than once (name.oft.1, name.oft.1.stm, name.oft.1.x64) and may
    # draw with any of them, so every copy the game has gets the Arabic font.
    copies = [c for n in names for c in _font_copies(n) if c not in names and path_hashes(c) in present]
    if copies:
        log(f'Also {len(copies)} other copies of those fonts in the game\'s paks.')
    return found + list(dict.fromkeys(copies))


def _font_copies(name: str) -> list:
    base = re.sub(r'\.(?:stm|x64)$', '', name, flags=re.I)
    return [base, base + '.stm', base + '.x64']


def make_oft(font: Path, args, out: Path) -> bytes:
    """Our font in the game's .oft container: made here, or by --font-converter-cmd."""
    if not args.font_converter_cmd:
        return reefont.encode_oft(font.read_bytes())
    made = out / 'oft' / (font.stem + '.oft.1')
    made.parent.mkdir(parents=True, exist_ok=True)
    made.unlink(missing_ok=True)
    reefont.convert_with(args.font_converter_cmd, font, made)
    return made.read_bytes()


def build_reengine(source, rows, args, out: Path, payload: Path, log):
    """The game's message files with the Arabic in them, packed into one RE Engine .pak."""
    stage = out / 'stage' / 're'
    shutil.rmtree(stage, ignore_errors=True)
    stage.mkdir(parents=True)
    # Only this build's edited dumps, so none from an earlier build is mistaken for this one's.
    shutil.rmtree(out / 'msg-edited', ignore_errors=True)
    # Older RE Engine games can't join Arabic letters or lay them right to left;
    # newer ones with an Arabic option can (--no-shape).
    compiler = ArabicCompiler(max_line=args.max_line) if args.shape is not False else None
    # Which of the game's fonts get the Arabic font: .oft fonts by name (--font-targets,
    # a file list), or else plain font files found in the game's paks.
    oft_targets = re_font_targets(args, source, log) if not args.no_fonts and compiler else []
    args.fonts_used = oft_targets
    plain_fonts = []
    if not oft_targets and source.game_paks and not args.no_fonts and compiler:
        try:
            plain_fonts = remsg.find_fonts(source.game_paks, log)
        except remsg.MsgError as err:
            raise BuildError(str(err)) from None
    if args.require_fonts and compiler and not (oft_targets or plain_fonts):
        raise BuildError('GameShelf doesn\'t know this game\'s font files yet, so its Arabic would show as boxes. '
                         'Its fonts can be added with --pak-list or --font-targets.')
    # The game lines text up on the left. With our font in the game, each line can
    # be padded so the lines of a text end together on the right, as Arabic should.
    widths = line_widths(font_files(args)[0], log) if (oft_targets or plain_fonts) and args.align_right else None
    languages = args.msg_language or ['English']
    arabic = {r.key: r.arabic for r in rows if r.arabic and r.key}
    waiting = []
    untouched = 0
    for dump in source.msg_dumps:
        texts = {guid: (shape_re_text(arabic[f'{dump.in_pak}#{guid}'], compiler, widths) if compiler else arabic[f'{dump.in_pak}#{guid}'])
                 for guid in dump.english if f'{dump.in_pak}#{guid}' in arabic}
        if not texts:
            # No Arabic in this file: the game keeps its own, and the patch doesn't carry a copy.
            untouched += 1
            continue
        edited = out / 'msg-edited' / f'{dump.in_pak}.{dump.kind}'
        changed = remsg.write_dump(dump, texts, languages, edited)
        log(f'{dump.in_pak}: {changed} lines in Arabic ({" and ".join(languages)}{", shaped" if compiler else ""}).')
        if args.msg_tool:
            try:
                remsg.rebuild_msg(args.msg_tool, dump, edited, stage / dump.in_pak)
            except remsg.MsgError as err:
                raise BuildError(str(err)) from None
        else:
            waiting.append(edited)
    if untouched:
        log(f'{untouched} message files have no Arabic yet and stay as the game\'s own.')
    if waiting:
        raise BuildError(f'The Arabic is in the dumps in {out / "msg-edited"}. Give --msg-tool (REMSG_Converter\'s src/main.py, '
                         'or its .exe) to turn them into .msg files, then run again.')
    extra = [(Path(path), in_pak) for path, in_pak in source.msg_files] if args.msg_prebuilt else []
    # The Arabic font, made into the game's .oft font container, under the names
    # of the game's own fonts (from --font-targets or a file list). Only our
    # font is packed; the game's fonts are never read.
    if oft_targets:
        regular, bold, _ = font_files(args)
        made = {}
        for name in oft_targets:
            face = bold if RE_BOLD_FONT.search(Path(name).name) else regular
            if face not in made:
                try:
                    made[face] = make_oft(face, args, out)
                except reefont.FontError as err:
                    raise BuildError(str(err)) from None
            target = stage / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(made[face])
        log(f'Put the {regular.stem} font, as .oft, in place of the game\'s {len(oft_targets)} fonts: '
            + ', '.join(sorted({Path(n).name.split('.')[0] for n in oft_targets})))
    elif source.game_paks and not args.no_fonts and compiler:
        if plain_fonts:
            regular, _, _ = font_files(args)
            for lower, upper in plain_fonts:
                target = stage / f'fonts/{lower:08x}-{upper:08x}.font'
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(regular, target)
            log(f'Put the {regular.stem} font in place of the game\'s {len(plain_fonts)} font files.')
        else:
            log('The game\'s fonts aren\'t plain font files. Give --pak-list (a list of the game\'s file names) or --font-targets '
                'so the Arabic font goes in as the game\'s .oft fonts; otherwise Arabic shows as boxes.')
    if args.natives:
        found = [(p, remsg.pak_path(p)) for p in sorted(Path(args.natives).rglob('*')) if p.is_file()]
        if any(in_pak is None for _, in_pak in found):
            raise BuildError('--natives should be a natives folder (or hold one): its files keep their natives/... paths in the pak.')
        extra += found
    for path, in_pak in extra:
        target = stage / in_pak
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(path, target)
    files = [(remsg.pak_entry(p.relative_to(stage).as_posix()), p.read_bytes()) for p in sorted(stage.rglob('*')) if p.is_file()]
    if files:
        files.append((remsg.PATCH_MARKER, remsg.PATCH_MARKER_TEXT))
    if not files:
        raise BuildError('There\'s nothing to put in the pak.')
    (payload / RE_PAK_NAME).write_bytes(write_pak(files))
    log(f'Packed {len(files)} files into {RE_PAK_NAME}; GameShelf gives it the game\'s next patch number when it adds it.')


def find_packer(args):
    if args.packer_path:
        return args.packer or ('unrealpak' if 'unrealpak' in Path(args.packer_path).name.lower() else 'repak'), args.packer_path
    for kind, names in (('repak', ['repak']), ('unrealpak', ['UnrealPak', 'UnrealPak.exe'])):
        if args.packer and args.packer != kind:
            continue
        for name in names:
            found = shutil.which(name)
            if found:
                return kind, found
    return None, None


def build_unreal(source, translations: dict, args, payload: Path, stage_root: Path, log):
    if source.locres is None:
        raise BuildError('An Unreal pack needs the game\'s English .locres as the source.')
    in_pak = args.locres_path or source.locres_path
    if not in_pak:
        raise BuildError('Say where the .locres goes in the game with --locres-path, e.g. MyGame/Content/Localization/Game/en/Game.locres.')
    in_pak = PurePosixPath(in_pak.replace('\\', '/').lstrip('/'))
    if '..' in in_pak.parts:
        raise BuildError('--locres-path must stay inside the game.')
    compiler = ArabicCompiler(max_line=args.max_line) if args.shape else None
    texts = {key: (compiler(arabic) if compiler else arabic) for key, arabic in translations.items()}
    stage = stage_root / 'pak'
    shutil.rmtree(stage, ignore_errors=True)
    target = stage.joinpath(*in_pak.parts)
    target.parent.mkdir(parents=True)
    target.write_bytes(locres_format.write(source.locres.translated(texts)))
    log(f'Staged {in_pak} with {len(texts)} Arabic lines.')
    # The Arabic font, under the names of the game's own font files: the pak
    # loads after the game's, so the game draws its text with it.
    staged = [(target, in_pak)]
    fonts = unreal_font_targets(args, log)
    if fonts:
        regular, bold, license_text = font_files(args)
        for font in fonts:
            face = bold if BOLD_NAME.search(font.stem) else regular
            path = stage.joinpath(*font.parts)
            path.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(face, path)
            staged.append((path, font))
        if license_text:
            shutil.copyfile(license_text, payload.parent / 'FONT-LICENSE.txt')
        log(f'Staged the {regular.stem} font as the game\'s {len(fonts)} font files: ' + ', '.join(f.name for f in fonts))

    kind, exe = find_packer(args)
    if not exe:
        raise BuildError(f'The .locres is staged in {stage}, but no pak tool was found. Install repak '
                         '(github.com/trumank/repak) or give --packer-path to UnrealPak from your Unreal Engine install, then run again.')
    out_pak = payload / PAK_NAME
    if kind == 'unrealpak':
        listing = stage_root / 'unrealpak-files.txt'
        listing.write_text(''.join(f'"{path}" "{args.mount_point}{inside.as_posix()}"\n' for path, inside in staged), encoding='utf-8')
        command = [exe, str(out_pak), f'-create={listing}']
    else:
        command = [exe, 'pack', '--version', args.pak_version, '--mount-point', args.mount_point, str(stage), str(out_pak)]
    log('Packing: ' + ' '.join(command))
    result = subprocess.run(command, capture_output=True, text=True)
    if result.returncode != 0 or not out_pak.exists():
        raise BuildError(f'{kind} failed: {(result.stderr or result.stdout).strip()[-500:]}')


def sign(pack_dir: Path, args, kind: str):
    node = os.environ.get('GAMESHELF_NODE') or shutil.which('node')
    if not node:
        raise BuildError('Signing needs Node.js (node) on the PATH.')
    command = [node, str(SIGNER), 'make', str(pack_dir), '--engine', kind, '--id', args.id, '--version', args.version, '--key', args.key]
    command += ['--steam-app-id', str(args.steam_app_id)] if args.steam_app_id else ['--game-id', args.game_id]
    if args.title:
        command += ['--title', args.title]
    if kind == 'overlay':
        for flag, value in (('--threshold', args.threshold), ('--region', args.region), ('--text-luma', args.text_luma)):
            if value is not None:
                command += [flag, str(value)]
        if args.dark_text:
            command += ['--dark-text']
    if kind == 'unity':
        if args.font_bundle:
            command += ['--font-bundle', Path(args.font_bundle).name]
        ugui_font = None if args.no_ugui_font else args.ugui_font
        for flag, value in (('--backend', args.backend), ('--unity', args.unity_version), ('--ugui-font', ugui_font)):
            if value:
                command += [flag, value]
    if kind == 'godot':
        command += ['--godot', str(args.godot)]
    result = subprocess.run(command, capture_output=True, text=True)
    if result.returncode != 0:
        raise BuildError(f'Signing failed: {(result.stderr or result.stdout).strip()}')
    return result.stdout.strip()


def build(args, log=print) -> Path:
    out = Path(args.out or REPO / 'build' / 'arabic-packs' / args.id)
    out.mkdir(parents=True, exist_ok=True)
    try:
        source = read_source(args.source, locres_path=args.locres_path, msg_path=args.msg_path)
    except (SourceError, locres_format.LocResError) as err:
        raise BuildError(str(err)) from None
    for note in source.notes:
        log(note)
    kind = args.kind or source.engine or 'overlay'
    args.resolved_kind = kind
    if source.game_paks:
        try:
            source.msg_files = remsg.extract_messages(source.game_paks, out / 'msg-from-game', log)
        except remsg.MsgError as err:
            raise BuildError(str(err)) from None
        if not source.msg_files:
            raise BuildError('Found no message files in the game\'s paks.')
    # RE Engine message files without dumps (for an RE Engine pack, or an
    # overlay pack made from the same text) are read with REMSG_Converter.
    if source.msg_files and not source.msg_dumps and not (kind == 'reengine' and args.msg_prebuilt):
        game_paks = source.game_paks
        source = dump_messages(source, args, out, log)
        source.game_paks = game_paks  # still needed, for the game's fonts
    # RE Engine message files that already hold the Arabic need no translating.
    prebuilt = kind == 'reengine' and args.msg_prebuilt and not source.rows
    rows = source.rows[:args.limit] if args.limit else source.rows
    if args.translations:
        apply_reviewed(rows, args.translations, log)
    if not rows and not prebuilt:
        raise BuildError('Found no English lines to translate.')
    failed = {}
    if rows:
        log(f'{len(rows)} English lines; making a{"n" if kind[0] in "aeiou" else ""} {kind} pack.')
        try:
            failed = translate_rows(rows, args, out, log)
        except TranslationError as err:
            raise BuildError(str(err)) from None
        review = out / 'translations.csv'
        try:
            if not args.translations or Path(args.translations).resolve() != review.resolve():
                keep_previous(review, log)
            write_review(rows, failed, review, keyed=source.keyed)
            log(f'Wrote {review}: read it, fix what needs fixing, and run again with --translations to rebuild.')
        except PermissionError:
            # Windows won't let a file open in Excel be replaced.
            if args.review:
                raise BuildError(f'{review} is open in another program (Excel?). Close it and run again.') from None
            log(f'{review} is open in another program (Excel?), so it was left as it is. The pack is made all the same.')
        if failed:
            log(f'{len(failed)} lines couldn\'t be translated cleanly; they\'re left out (see the "problem" column).')
    if args.review:
        return out

    if not args.key:
        raise BuildError('Give --key (pack-signing.key) to sign the pack.')
    pairs = [(r.source, r.arabic) for r in rows if r.arabic]
    if len(pairs) < len(rows):
        log(f'{len(rows) - len(pairs)} lines have no Arabic and are left out of the pack.')
    if not pairs and not prebuilt:
        raise BuildError('No lines have Arabic, so there\'s nothing to pack.')
    pack_dir = out / 'pack'
    shutil.rmtree(pack_dir, ignore_errors=True)
    payload = pack_dir / 'payload'
    payload.mkdir(parents=True)
    compiled_dir = out / 'compiled'
    compiled_dir.mkdir(exist_ok=True)

    if kind == 'overlay':
        table, warnings = build_table(pairs)
        for warning in warnings:
            log(f'fingerprints: {warning}')
        (payload / 'fingerprints.json').write_text(json.dumps(table, ensure_ascii=False, separators=(',', ':')), encoding='utf-8')
    elif kind == 'unity':
        build_unity(pairs, args, payload, compiled_dir, log)
    elif kind == 'renpy':
        build_renpy(pairs, args, payload, log)
    elif kind == 'godot':
        build_godot(rows, source, args, payload, log)
    elif kind == 'reengine':
        build_reengine(source, rows, args, out, payload, log)
    else:
        translations = {r.key: r.arabic for r in rows if r.arabic and r.key}
        build_unreal(source, translations, args, payload, out / 'stage', log)

    if args.shared and rows:
        report_lines(rows, args, kind, log)
    log(sign(pack_dir, args, kind))
    log(f'Done: {pack_dir}{f" ({len(pairs)} lines)" if pairs else ""}. Add it in GameShelf under App settings, Arabic subtitle packs.')
    return pack_dir


def main(argv=None) -> int:
    args = parse_args(argv)
    try:
        build(args)
    except BuildError as err:
        print(f'error: {err}', file=sys.stderr)
        return 1
    return 0


