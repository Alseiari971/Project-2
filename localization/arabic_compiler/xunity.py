"""Translation files for XUnity.AutoTranslator, the Unity text replacement plugin.

Each line is ``original=translation``. XUnity looks the game's English text up
in these files as it's drawn, so a dictionary lookup is all that happens at
runtime. Escaping matches XUnity's own (TextHelper.Escape): backslashes, "=",
line breaks, and "//" (which would otherwise start a comment).
"""

from __future__ import annotations

from pathlib import Path

FILE_NAME = '_AutoGeneratedTranslations.txt'


def escape(text: str) -> str:
    out = []
    i = 0
    while i < len(text):
        ch = text[i]
        if ch == '/' and text[i + 1:i + 2] == '/':
            out.append('\\/\\/')
            i += 2
            continue
        out.append({'\\': '\\\\', '=': '\\=', '\n': '\\n', '\r': '\\r'}.get(ch, ch))
        i += 1
    return ''.join(out)


def translation_line(original: str, translation: str) -> str:
    return f'{escape(original)}={escape(translation)}'


def write_translations(pairs, path: Path, *, title: str = 'GameShelf Arabic') -> int:
    """Writes (original, compiled Arabic) pairs; returns how many lines it wrote.

    Empty originals and lines that translate to themselves are skipped. When an
    original appears twice, the later translation wins, as it would in XUnity.
    """
    entries: dict = {}
    for original, translation in pairs:
        if original and translation and original != translation:
            entries[original] = translation
    lines = [f'// {title}: compiled for engines without Arabic shaping. Do not edit by hand;',
             '// change the source translations and compile again.']
    lines += [translation_line(o, t) for o, t in entries.items()]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    return len(entries)
